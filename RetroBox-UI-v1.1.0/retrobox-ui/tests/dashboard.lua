return function(Mock,Library,test)
    local function fixture()
        local w=Library:CreateWindow({Id="dashboard-test",FileStorage=false,Settings=false,ReducedMotion=true})
        return w,w:CreateTab("Dashboard"):CreateSection("Metrics")
    end
    local function tick(dt) Mock.pump(dt or .1); Mock.Services.RunService.RenderStepped:Fire(dt or .1); Mock.pump() end
    local function finish(w) w:Destroy(); Mock.pump(100); assert(Mock.Connections==0); Mock.Warnings={} end
    test("value formats cover raw, compact, percent, time and custom values",function()
        assert(Library:FormatValue(1234567,"Compact",2)=="1.23M")
        assert(Library:FormatValue(-1500,"Compact")=="-1.5K")
        assert(Library:FormatValue(45.25,"Percent",2)=="45.25%")
        assert(Library:FormatValue(3661,"Time")=="01:01:01" and Library:FormatValue(61,"Time")=="01:01")
        assert(Library:FormatValue(42,"Raw")=="42" and Library:FormatValue(nil)=="—")
        assert(Library:FormatValue(3,function(v) return v.." items" end)=="3 items")
        assert(not pcall(function() Library:FormatValue(1,"bad") end))
    end)
    test("stat cards bind live values, status, units and bounded sparklines",function()
        local w,s=fixture(); local state=w:CreateState(1200)
        local c=s:AddStatCard({Id="stat",State=state,Format="Compact",Unit="items",Subtitle="Simulated",Sparkline=true,MaxPoints=4})
        tick(); assert(c:GetValue()==1200 and c.ValueLabel.Text=="1.2K" and c.UnitLabel.Text=="items" and not c.Persist)
        state:Set(3400); c:SetTrend(-100,"-100 today"):SetSubtitle("Current"):SetUnit("coins"); tick()
        assert(c.ValueLabel.Text=="3.4K" and c.TrendLabel.Text=="-100 today" and c.SubtitleLabel.Text=="Current")
        c:SetLoading(true); tick(); assert(c.ValueLabel.Text==w:_text("loading"))
        c:SetLoading(false):SetUnavailable(true,"Offline"); tick(); assert(c.ValueLabel.Text=="Offline")
        c:SetUnavailable(false); for i=1,8 do c:AddPoint(i) end; tick()
        assert(#c:GetHistory()==4 and c:GetHistory()[1].Value==5 and #c._sparkPool==3)
        local first=c._sparkPool[1]; c:AddPoint(9); tick(); assert(c._sparkPool[1]==first)
        local config=Mock.Services.HttpService:JSONDecode(w:ExportConfig()); assert(not config.Flags.stat)
        c:Destroy(); assert(next(state._listeners)==nil); finish(w)
    end)
    test("line charts retain chronological points and reuse a bounded pool",function()
        local w,s=fixture(); local c=s:AddLineChart({MaxPoints=5,Data={{Value=1,Label="A"},2,3},ShowLegend=true,Legend="Rate"})
        tick(); assert(c.ChartType=="Line" and #c._pool==2 and c.FirstLabel.Text=="A" and c.Legend.Text=="Rate")
        local first=c._pool[1]; for i=4,100 do c:AddPoint(i,tostring(i)) end
        assert(#c:GetValue()==5 and c:GetValue()[1].Value==96); tick()
        assert(#c._pool==4 and c._pool[1]==first and c.LastLabel.Text=="100")
        c:SetMaxPoints(3); tick(); assert(#c._pool<=3 and #c:GetValue()==3)
        c:Clear(); tick(); assert(c.EmptyLabel.Visible and not c._pool[1].Visible); finish(w)
    end)
    test("bar charts include zero and represent negative values",function()
        local w,s=fixture(); local c=s:AddBarChart({Data={-10,5,20}}); tick()
        assert(c.Bounds.Min==-10 and c.Bounds.Max==20 and #c._pool==3)
        assert(c._pool[1].Size.Y.Offset>0 and c._pool[2].Size.Y.Offset>0 and c._pool[1].Position.Y.Offset>c._pool[2].Position.Y.Offset)
        c:SetData({5,5}); tick(); assert(c.Bounds.Min==0 and c.Bounds.Max==5)
        c:SetRange(-100,100); tick(); assert(c.Bounds.Min==-100 and c.Bounds.Max==100); finish(w)
    end)
    test("progress and sparkline charts support clamping and specialized layout",function()
        local w,s=fixture(); local p=s:AddProgressChart({Value=25}); local line=s:AddSparkline({Data={2,2,2}}); tick()
        assert(p.ChartType=="Progress" and p.ProgressLabel.Text=="25%" and p._pool[1].Size.X.Scale==.25)
        p:SetValue(200); tick(); assert(p:GetValue()==100 and p.ProgressLabel.Text=="100%")
        p:SetRange(0,50); tick(); assert(p:GetValue()==50 and p._pool[1].Size.X.Scale==1)
        assert(line.ChartType=="Sparkline" and not line.ShowGrid and not line.ShowLabels and line.Bounds.Min<2 and line.Bounds.Max>2)
        assert(not pcall(function() p:AddPoint(1) end)); finish(w)
    end)
    test("charts coalesce high frequency draws while exposing current data",function()
        local w,s=fixture(); local c=s:AddLineChart({Data={1,2},RefreshRate=10}); tick()
        local count=0; local draw=c._draw; c._draw=function(self) count=count+1; return draw(self) end
        for i=3,50 do c:AddPoint(i) end
        assert(c:GetValue()[#c:GetValue()].Value==50 and count==0 and w:GetRuntimeStats().QueuedVisuals==1)
        tick(.05); assert(count==0); tick(.06); assert(count==1 and w:GetRuntimeStats().QueuedVisuals==0)
        c:AddPoint(51); c:Destroy(); assert(w:GetRuntimeStats().QueuedVisuals==0); finish(w)
    end)
    test("invalid chart and card options do not register partial components",function()
        local w,s=fixture(); local count=#s.Controls
        for _,options in ipairs({{Type="Pie"},{MaxPoints=0},{Precision=7},{Thickness=0},{RefreshRate=0},{Color="invalid"},{Format="bad"}}) do
            assert(not pcall(function() s:AddChart(options) end) and #s.Controls==count)
        end
        assert(not pcall(function() s:AddStatCard({Trend="bad"}) end) and #s.Controls==count)
        local c=s:AddLineChart({Data={1,2}}); local before=c:GetValue()
        assert(not pcall(function() c:SetData({1,0/0}) end) and #c:GetValue()==#before)
        assert(not pcall(function() c:SetData({[1]=1,[3]=2}) end)); finish(w)
    end)
    test("charts and cards fit rows and release resize subscriptions",function()
        local w,s=fixture(); local row=s:CreateRow({StackAt=500}); local a=row:AddStatCard({Value=42}); local b=row:AddSparkline({Data={1,2,3}})
        row.Frame._props.AbsoluteSize=Vector2.new(350,200); row:_layout(); assert(row.Stacked and a.Frame.Size.X.Scale==1 and b.Frame.Size.X.Scale==1)
        row.Frame._props.AbsoluteSize=Vector2.new(800,200); row:_layout(); assert(not row.Stacked and a.Frame.Size.X.Scale==.5)
        local signal=b.Plot:GetPropertyChangedSignal("AbsoluteSize"); b:Destroy(); signal:Fire(); tick()
        assert(w:GetRuntimeStats().QueuedVisuals==0); finish(w)
    end)
    test("custom formatting errors are isolated from data updates and other controls",function()
        local w,s=fixture(); local c=s:AddStatCard({Id="format",Format=function() error("formatter failed") end})
        c:SetValue(42,true); local other=s:AddToggle({Default=true}); tick()
        assert(c:GetValue()==42 and other:GetValue() and w:GetDiagnostics()[1].Phase=="Render"); finish(w)
    end)
end
