return function(Mock,Library,test)
    local function count(t) local n=0; for _ in pairs(t) do n=n+1 end; return n end
    local function fixture(options)
        options=options or {}; options.Id=options.Id or "pixel-test"; options.ReducedMotion=true; options.FileStorage=false
        local w=Library:CreateWindow(options)
        local tab=w:CreateTab({Title="Main",Icon="home"})
        return w,tab,tab:CreateSection({Title="Tools",Icon="code"})
    end
    local function finish(w)
        w:Destroy(); Mock.pump(40); assert(Mock.Connections==0 and next(w._icons)==nil)
    end
    test("pixel catalog is embedded, sorted, bounded and returned as copies",function()
        local names=Library:GetIconNames(); assert(#names==46)
        for index,name in ipairs(names) do
            if index>1 then assert(names[index-1]<name) end
            local rows=Library:GetIcon(name); assert(#rows==12 and #rows[1]==12)
            for _,row in ipairs(rows) do assert(#row==12 and not row:find("[^%.#ahsmgr]")) end
            rows[1]="mutated"; assert(Library:GetIcon(name)[1]~="mutated")
        end
        assert(Library:GetIcon("missing")==nil)
    end)
    test("title, tabs, categories and standard actions have default pixel art",function()
        local w=Library:CreateWindow({Id="pixel-defaults",FileStorage=false})
        local tab=w:CreateTab("Main"); local section=tab:CreateSection("Tools")
        assert(w.Icon:GetAttribute("RetroBoxIcon")=="retrobox")
        assert(tab.Icon:GetAttribute("RetroBoxIcon")=="grid" and section.Icon:GetAttribute("RetroBoxIcon")=="folder")
        assert(w._settingsTab.Icon:GetAttribute("RetroBoxIcon")=="settings")
        assert(w.CloseButton.Text=="" and w.SettingsButton.Text=="")
        assert(w.Search:FindFirstChild("TextPadding").PaddingLeft.Offset==30)
        assert(w.PixelMotif.Visible and w.PixelSeal.Visible)
        local c=section:AddToggle({Default=true}); assert(c._checkIcon.Frame.Visible and c.Button.Text=="")
        finish(w)
    end)
    test("control icons reserve title space including sliders and inline bindings",function()
        local w,tab,s=fixture()
        local t=s:AddToggle({Icon="bolt",Keybind=Enum.KeyCode.F})
        local slider=s:AddSlider({Icon="sliders"})
        assert(t.TitleLabel.Position.X.Offset==22 and t.TitleLabel.Size.X.Offset==-184)
        assert(slider.TitleLabel.Position.X.Offset==22 and slider.TitleLabel.Size.X.Offset==-107)
        local c=s:AddButton({Icon="save",Disabled=true})
        assert(c._titleIcon.Nodes[1].BackgroundTransparency==.5)
        c:SetDisabled(false); assert(c._titleIcon.Nodes[1].BackgroundTransparency==0)
        t:SetIcon(false); assert(t.TitleLabel.Position.X.Offset==0 and t.TitleLabel.Size.X.Offset==-162)
        t:SetIcon("eye"); t:SetIcon("target"); assert(t.TitleLabel.Position.X.Offset==22 and t.TitleLabel.Size.X.Offset==-184)
        tab:SetTitle("Renamed"); s:SetTitle("Renamed tools"); t:SetTitle("Feature")
        assert(tab.Label.Text=="Renamed" and s.Header.Text=="RENAMED TOOLS" and t.TitleLabel.Text=="Feature")
        finish(w)
    end)
    test("pixel icons follow theme roles and active tab contrast",function()
        local w,tab,s=fixture(); local c=s:AddToggle({Icon="eye"})
        for _,theme in ipairs(Library:GetThemeNames()) do
            w:SetTheme(theme)
            assert(tab._titleIcon.Foreground[1].BackgroundColor3==w.Palette.AccentText)
            assert(c._titleIcon.Foreground[1].BackgroundColor3==w.Palette.Text)
        end
        w:SetAccent("#FFFFFF"); assert(tab._titleIcon.Foreground[1].BackgroundColor3==w.Palette.AccentText)
        local other=w:CreateTab({Title="Other",Icon="home"}); other:Select()
        assert(tab._titleIcon.Foreground[1].BackgroundColor3==w.Palette.Text)
        finish(w)
    end)
    test("custom patterns update mounted icons and invalid patterns are atomic",function()
        local rows={".#..","###.",".#..","...."}
        assert(Library:RegisterIcon("test_custom",rows)==Library)
        rows[1]="...."; assert(Library:GetIcon("test_custom")[1]==".#..")
        local w,tab,s=fixture(); local c=s:AddLabel({Icon="test_custom"})
        local nodes=c._titleIcon.Nodes
        Library:RegisterIcon("test_custom",{"a...",".h..","..#.","...g"})
        assert(c.Icon:GetAttribute("RetroBoxIcon")=="test_custom" and c._titleIcon.Nodes~=nodes)
        assert(not pcall(function() Library:RegisterIcon("test_custom",{"....","...","....","...."}) end))
        assert(Library:GetIcon("test_custom")[1]=="a...")
        for _,rowsBad in ipairs({{}, {"xxxx","....","....","...."}, {"....","....","....","...."}}) do
            assert(not pcall(function() Library:RegisterIcon("bad",rowsBad) end))
        end
        assert(not pcall(function() Library:RegisterIcon("Invalid name",{"####","####","####","####"}) end))
        finish(w)
    end)
    test("legacy text and image assets coexist with strict pixel names",function()
        local w,tab,s=fixture({Icon="rbxassetid://123"})
        assert(w._titleIcon.Nodes[1].Image=="rbxassetid://123")
        assert(w._titleIcon.Nodes[1].ResampleMode==Enum.ResamplerMode.Pixelated)
        tab:SetIcon("⚙"); assert(tab._titleIcon.Nodes[1].Text=="⚙")
        s:SetIcon(456); assert(s._titleIcon.Nodes[1].Image=="rbxassetid://456")
        w:SetIcon("pixel:retrobox"); local old=w._titleIcon.Nodes
        assert(not pcall(function() w:SetIcon("pixel:missing") end))
        assert(w._titleIcon.Nodes==old and w.Icon:GetAttribute("RetroBoxIcon")=="retrobox")
        w:SetIcon(nil); assert(not w.Icon.Visible and w.TitleLabel.Position.X.Offset==10)
        finish(w)
        local before=Mock.Connections
        assert(not pcall(function() Library:CreateWindow({Icon={},Id="invalid-icon"}) end))
        assert(before==Mock.Connections)
    end)
    test("default pixel art can be disabled without hiding explicit icons",function()
        local w,tab,s=fixture()
        local defaultTab=w:CreateTab("Default"); local c=s:AddToggle({Default=true,Icon="bolt"})
        w:SetPixelIcons(false); w:SetPixelDecorations(false)
        assert(not w.Icon.Visible and not defaultTab.Icon.Visible)
        assert(w.CloseButton.Text=="X" and w.SettingsButton.Text=="⚙")
        assert(w.Search:FindFirstChild("TextPadding").PaddingLeft.Offset==8)
        assert(tab.Icon.Visible and s.Icon.Visible and c.Icon.Visible)
        assert(c.Button.Text=="X" and not c._checkIcon.Frame.Visible)
        assert(not w.PixelMotif.Visible and not w.PixelSeal.Visible)
        w:SetPixelIcons(true); w:SetPixelDecorations(true)
        assert(w.Icon.Visible and defaultTab.Icon.Visible and c._checkIcon.Frame.Visible)
        w:Minimize(true); assert(not w.PixelMotif.Visible)
        w:Minimize(false); assert(w.PixelMotif.Visible)
        finish(w)
    end)
    test("pixel appearance persists, rejects invalid values and accepts old saves",function()
        local w,tab,s=fixture(); local toggle=s:AddToggle({Id="feature"})
        w:SetPixelIcons(false); w:SetPixelDecorations(false)
        local json=w:ExportConfig()
        w:SetPixelIcons(true); w:SetPixelDecorations(true)
        assert(w:ImportConfig(json,{Silent=true}) and not w.PixelIcons and not w.PixelDecorations)
        local bad=w:ExportConfig(true); bad.Appearance.PixelIcons="yes"; bad.Flags.feature.Value=true
        assert(not w:ImportConfig(bad) and not toggle:GetValue() and not w.PixelIcons)
        local legacy=w:ExportConfig(true); legacy.Appearance.PixelIcons=nil; legacy.Appearance.PixelDecorations=nil
        w:SetPixelIcons(true); assert(w:ImportConfig(legacy,{Silent=true}) and w.PixelIcons and not w.PixelDecorations)
        w:Reset(true); assert(w.PixelIcons and w.PixelDecorations)
        assert(w._settingsControls.PixelIcons:GetValue() and w._settingsControls.PixelDecorations:GetValue())
        finish(w)
    end)
    test("notifications and dialogs accept pixel art and respect default preferences",function()
        local w=fixture()
        local note=w:Notify({Kind="success"}); assert(note.Icon:GetAttribute("RetroBoxIcon")=="success")
        local dialog=w:Confirm({Content="Confirm?",Kind="danger"})
        assert(dialog.Icon:GetAttribute("RetroBoxIcon")=="warning"); dialog:Close()
        local explicit=w:Dialog({Icon="star",Buttons={{Text="OK"}}}); assert(explicit.Icon:GetAttribute("RetroBoxIcon")=="star")
        local before=count(w._icons)
        assert(not pcall(function() w:Dialog({Icon="pixel:missing",Buttons={{Text="OK"}}}) end))
        assert(not explicit.Destroyed and count(w._icons)==before)
        explicit:Close(); w:SetPixelIcons(false)
        assert(not note.Icon.Visible)
        assert(not w:Notify({Icon=false}).Icon.Visible)
        assert(w:Notify({Icon="star"}).Icon.Visible)
        finish(w)
    end)
    test("icon replacements and transient UI release objects and connections",function()
        local w,tab,s=fixture(); local c=s:AddToggle({Icon="bolt"})
        local handles=count(w._icons); local connections=Mock.Connections
        local old=c._titleIcon.Nodes[1]
        for i=1,30 do
            c:SetIcon(i%2==0 and "eye" or "code")
            local note=w:Notify({Icon="info"}); note:Destroy()
            local dialog=w:Confirm({Content="Test"}); dialog:Close()
        end
        assert(not old.Parent and w._skin[old]==nil)
        assert(count(w._icons)==handles and Mock.Connections==connections)
        for _,node in ipairs(c._titleIcon.Nodes) do assert(node.Size.X.Offset%1==0 and node.Position.X.Offset%1==0) end
        finish(w)
    end)
end
