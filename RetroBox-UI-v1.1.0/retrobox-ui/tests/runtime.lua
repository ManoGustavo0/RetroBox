return function(Mock,Library,test)
    local function fixture(options)
        options=options or {}; options.Id="runtime-test"; options.FileStorage=false; options.ReducedMotion=true
        local w=Library:CreateWindow(options); return w,w:CreateTab("Main"):CreateSection("Main")
    end
    local function finish(w) w:Destroy(); Mock.pump(100); Mock.YieldingTasks=false; assert(Mock.Connections==0); Mock.Warnings={} end
    local function tick(dt) Mock.pump(dt or .1); Mock.Services.RunService.RenderStepped:Fire(dt or .1); Mock.pump() end
    test("ColorPicker keeps left HEX and right swatch disjoint",function()
        local w,s=fixture(); local c=s:AddColorPicker({Default="#ABCDEF"}); local width=c.Preview.Parent.AbsoluteSize.X
        assert(c.Preview.Position.X.Scale==1 and c.PreviewText.Position.X.Offset+c.PreviewText.AbsoluteSize.X<=width-44)
        assert(c.PreviewText.Text=="#ABCDEF" and c.TitleLabel.Position.Y.Offset==0)
        c:SetColor("#112233"); c:SetOpen(true); assert(c.PreviewText.Text=="#112233" and c.Open)
        assert(w._settingsControls.Accent.Preview.Position.X.Scale==1); finish(w)
    end)
    test("resources replace keys and clean exactly once in reverse order",function()
        local w=fixture(); local order={}; local scope=w:CreateScope()
        assert(not pcall(function() scope:Child({CancelOnHide="invalid"}) end))
        scope:Add(function() order[#order+1]="old" end,nil,"key"); scope:Add(function() order[#order+1]="new" end,nil,"key")
        local object=Instance.new("Frame"); object.Parent=w.Root; scope:Add(object)
        local c=Mock.signal():Connect(function() end); scope:Add(c)
        scope:Add(function() order[#order+1]="last" end); scope:Clean(); scope:Clean()
        assert(table.concat(order,",")=="old,last,new" and not object.Parent and not c.Connected)
        scope:Destroy(); scope:Add(function() order[#order+1]="late" end); assert(order[4]=="late"); finish(w)
    end)
    test("hide and disable cleanup policies are explicitly opt in",function()
        local w,s=fixture(); local a,b,c=0,0,0
        w:Manage(function() a=a+1 end); w:CreateScope({CancelOnHide=true}):Add(function() b=b+1 end)
        local t=s:AddToggle({Default=true}); t:CreateScope({CancelOnDisable=true}):Add(function() c=c+1 end)
        w:Minimize(true); assert(a+b+c==0); w:Hide(); assert(a==0 and b==1)
        t:SetDisabled(true); assert(c==1); finish(w); assert(a==1)
    end)
    test("states copy data, reject cycles and release observers",function()
        local state=Library:CreateState({Count=1}); local n=0; local sub=state:Subscribe(function(v) n=v.Count end,true)
        local v=state:Get(); v.Count=2; assert(state:Get().Count==1)
        state:Set({Count=3}); assert(n==3 and not state:Set({Count=3})); sub:Disconnect()
        state:Set({Count=4}); assert(n==3); local cyc={}; cyc.self=cyc
        assert(not pcall(function() state:Set(cyc) end)); state:Destroy(); assert(not sub.Connected)
    end)
    test("batch flags validate atomically and notify complete snapshots",function()
        local w,s=fixture(); local a=s:AddToggle({Id="a"}); local b=s:AddSlider({Id="b",Default=1}); local seen
        w:GetFlagState("a"):Subscribe(function() seen=w:GetFlag("b") end)
        assert(w:SetFlags({a=true,b=50}) and seen==50)
        assert(not w:SetFlags({a=false,b="bad"}) and a:GetValue() and b:GetValue()==50)
        local state=w:CreateState(0); local calls=0; state:Subscribe(function() calls=calls+1 end)
        Library:Batch(function() state:Set(1); state:Set(2); state:Set(3) end)
        assert(calls==1 and state:Get()==3); finish(w)
    end)
    test("profiles notify flag observers after all saved values are applied",function()
        local w,s=fixture(); local a=s:AddToggle({Id="a"}); local b=s:AddSlider({Id="b",Default=1})
        a:SetValue(true,true); b:SetValue(75,true); local json=w:ExportConfig(); a:SetValue(false,true); b:SetValue(2,true)
        local seen; w:GetFlagState("a"):Subscribe(function() seen=w:GetFlag("b") end)
        assert(w:ImportConfig(json,{Silent=true}) and seen==75); finish(w)
    end)
    test("two way bindings and AND conditions update and own their listeners",function()
        local w,s=fixture(); local value=w:CreateState(5); local enabled=s:AddToggle({Id="enabled"})
        local slider=s:AddSlider({State=value,Id="slider"}); slider:SetValue(25); Mock.pump(); assert(value:Get()==25)
        value:Set(50); assert(slider:GetValue()==50)
        slider:SetValue(60,true); assert(value:Get()==60)
        value:Set(200); assert(slider:GetValue()==100 and value:Get()==100)
        local button=s:AddButton({DependsOn={Enabled={All={{Flag="enabled",Equals=true},{State=value,Test=function(v) return v>10 end}}},Reason="Enable first"}})
        assert(button.Disabled and button:GetTooltip().Text:find("Enable first",1,true)); enabled:SetValue(true,true); assert(not button.Disabled)
        value:Set(3); assert(button.Disabled); local cyc={}; cyc.All={cyc}; assert(not pcall(function() w:Condition(cyc) end))
        slider:Destroy(); button:Destroy(); assert(next(value._listeners)==nil); finish(w)
    end)
    test("reactive cycles and callback error history are bounded",function()
        local w=fixture(); local state=w:CreateState(0); state:Subscribe(function(v) state:Set(v+1) end); state:Set(1)
        assert(state:Get()<=130 and #w:GetDiagnostics()>=1)
        for i=1,70 do w:_protected(function() error("error "..i) end,{ControlId="test",Phase="Background"}) end
        assert(#w:GetDiagnostics()==64 and w:GetDiagnostics()[64].ControlId=="test"); finish(w)
    end)
    test("periodic tasks are idempotent and yielding callbacks never overlap",function()
        Mock.YieldingTasks=true; local w=fixture(); local count,active,maximum=0,0,0
        local job=w:CreateTask({Id="job",Interval=.1,Callback=function(ctx)
            active=active+1; maximum=math.max(maximum,active); count=count+1; task.wait(.5); active=active-1; ctx:ThrowIfCancelled()
        end})
        assert(job:Start() and job:Start()); tick(.1); assert(count==1 and active==1)
        tick(.1); tick(.1); assert(count==1); job:Stop(); job:Start(); tick(.1); assert(count==1)
        tick(.2); tick(.1); assert(maximum==1 and count==2); job:Stop(); tick(1)
        assert(not job:IsRunning() and not w:GetRuntimeStats().FrameConnection); finish(w)
    end)
    test("tasks survive hiding by default, stop on errors and support Stop All",function()
        local w=fixture(); local n=0; local job=w:CreateTask({Id="counter",Callback=function() n=n+1 end})
        job:Start(); w:Hide(); tick(); assert(n==1 and job.Requested)
        local hidden=w:CreateTask({Id="hide",CancelOnHide=true,Callback=function() end}); hidden:Start(); w:Hide(); assert(not hidden.Requested)
        local bad=w:CreateTask({Id="bad",Callback=function() error("background failure") end}); bad:Start(); tick()
        assert(not bad.Requested and w:GetDiagnostics()[1].Operation=="bad"); w:StopAll(); assert(not job.Requested); finish(w)
    end)
    test("action group replacement waits for cooperative cancellation",function()
        Mock.YieldingTasks=true; local w=fixture(); local log={}; local active,maximum=0,0
        local function op(name) return function(ctx)
            active=active+1; maximum=math.max(maximum,active); log[#log+1]=name; ctx:SetProgress(1,2,"first")
            task.wait(.5); active=active-1; ctx:ThrowIfCancelled(); ctx:SetProgress(2,2,"done"); return name
        end end
        local first=w:RunAction({Group="g",Callback=op("first")}); Mock.pump(); assert(first:GetStatus().Progress==.5)
        local no,why=w:RunAction({Group="g",Callback=op("reject")}); assert(not no and why:find("busy"))
        local ignore,reason=w:RunAction({Group="g",Policy="Ignore",Callback=op("ignore")}); assert(not ignore and reason=="ignored")
        local queued=w:RunAction({Group="g",Policy="Queue",Callback=op("queued")})
        local nextAction=w:RunAction({Group="g",Policy="Replace",Callback=op("next")})
        assert(first:GetStatus().Status=="Cancelling" and queued:GetStatus().Status=="Cancelled" and #log==1)
        Mock.pump(.6); assert(#log==2 and log[2]=="next" and maximum==1)
        Mock.pump(.6); assert(nextAction:GetStatus().Status=="Completed" and nextAction.Result=="next"); finish(w)
    end)
    test("failed actions release groups and terminal history stays bounded",function()
        local w=fixture(); local bad=w:RunAction({Group="g",Callback=function() return false,"failed" end}); Mock.pump()
        assert(bad:GetStatus().Status=="Failed" and bad.Error=="failed")
        assert(not pcall(function() bad.Status:Set({Status="Completed"}) end))
        for i=1,45 do w:RunAction({Group="g",Callback=function() return i end}); Mock.pump() end
        assert(#w._actionHistory==32 and next(w._actions)==nil and next(w._groups)==nil); finish(w)
    end)
    test("task cleanup policies work again after restarting and false flags clean coherently",function()
        local w,s=fixture(); local toggle=s:AddToggle({Id="enabled",Default=true}); s:AddSlider({Id="other"})
        local job=toggle:CreateTask({Id="owned",CancelOnDisable=true,CancelOnFalse=true,Callback=function() end})
        job:Start(); toggle:SetDisabled(true); assert(not job.Requested); toggle:SetDisabled(false)
        job:Start(); toggle:SetDisabled(true); assert(not job.Requested); toggle:SetDisabled(false)
        local seen; toggle:CreateScope({CancelOnFalse=true}):Add(function() seen=w:GetFlag("other") end)
        job:Start(); assert(w:SetFlags({enabled=false,other=75},{Silent=true})); assert(not job.Requested and seen==75)
        toggle:Destroy(); assert(job.Destroyed and not job:Start()); finish(w)
    end)
    test("managed buttons report cancellation and restore availability after yielding",function()
        Mock.YieldingTasks=true; local w,s=fixture(); local steps=0
        local b=s:AddButton({Id="action-button",Cancelable=true,Callback=function(_,ctx)
            steps=steps+1; ctx:SetProgress(1,2,"half"); task.wait(.5); ctx:ThrowIfCancelled(); return "ok"
        end})
        assert(b:Press() and not b:Press()); Mock.pump(); assert(steps==1 and b._busy and b:GetAction():GetStatus().Progress==.5)
        b:Cancel("user"); assert(b.Button.Text==w:_text("cancelling")); Mock.pump(1)
        assert(not b._busy and b:GetAction():GetStatus().Status=="Cancelled" and b.Button.Active)
        assert(b:Press()); Mock.pump(); Mock.pump(1); assert(b:GetAction().Result=="ok" and not b._busy)
        finish(w)
    end)
    test("OR and NOT dependencies and computed values see coherent batches",function()
        local w,s=fixture(); s:AddToggle({Id="a"}); s:AddToggle({Id="b"})
        local a,b=w:GetFlagState("a"),w:GetFlagState("b"); local count=w:Computed({a,b},function(x,y) return (x and 1 or 0)+(y and 1 or 0) end)
        local seen={}; count:Subscribe(function(value) seen[#seen+1]=value end)
        local c=s:AddButton({DependsOn={Visible={Any={{Flag="a"},{Flag="b"}}},Enabled={Not={Flag="b"}}}})
        assert(not c._visible and not c.Disabled); w:SetFlags({a=true,b=true},{Silent=true})
        assert(#seen==1 and seen[1]==2 and c._visible and c.Disabled)
        w:SetFlags({a=false,b=false},{Silent=true}); assert(seen[2]==0 and not c._visible and not c.Disabled)
        assert(not pcall(function() count:Set(1) end)); finish(w)
    end)
    test("callback adapters preserve arguments and debug diagnostics include state",function()
        local w,s=fixture({Debug=true,ErrorNotifications=false}); local executions=0; local events=0
        w:SetCallbackExecutor(function(callback,args,context) executions=executions+1; assert(context.Phase); return callback(table.unpack(args,1,args.n)) end)
        local subscription=w:OnError(function(record) events=events+1; assert(record.Time and record.Message) end)
        local t=s:AddToggle({Id="failure",Callback=function(value) assert(value); error("expected failure") end})
        t:SetValue(true); Mock.pump(); local record=w:GetDiagnostics()[1]
        assert(executions>0 and events==1 and record.ControlId=="failure" and record.State.Value==true and record.Traceback)
        w:_protected(function() error("repeat") end,{ControlId="failure",Phase="Callback"})
        assert(events==2 and #Mock.Warnings==1); subscription:Disconnect(); w:SetDebug(false); w:SetCallbackExecutor(nil)
        w:_protected(function() error("background") end,{Phase="Other"}); assert(not w:GetDiagnostics()[3].Traceback); finish(w)
    end)
    test("batch callback epochs discard older work and run against complete flags",function()
        local w,s=fixture(); local log={}; local a=s:AddSlider({Id="a",Callback=function(v) log[#log+1]={v,w:GetFlag("b")} end})
        s:AddSlider({Id="b"}); a:SetValue(1); assert(w:SetFlags({a=2,b=50})); Mock.pump()
        assert(#log==1 and log[1][1]==2 and log[1][2]==50)
        assert(w:SetFlags({a=3,b=60},{Silent=true})); Mock.pump(); assert(#log==1); finish(w)
    end)
end
