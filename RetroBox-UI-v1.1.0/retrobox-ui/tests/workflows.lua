-- End-to-end state flows for profiles, inputs and the new UI helpers.
return function(Mock,Library,test)
    local serial=0
    local function input(kind,key)
        return {UserInputType=kind,KeyCode=key or Enum.KeyCode.Unknown,Position=Vector2.new(120,140)}
    end
    local function fixture(options)
        serial=serial+1; options=options or {}; options.Id="workflow-"..serial
        if options.FileStorage==nil and not options.Storage then options.FileStorage=false end
        local window=Library:CreateWindow(options)
        local tab=window:CreateTab("Main"); local section=tab:CreateSection("Features")
        return window,section,tab
    end
    local function finish(window)
        window:Destroy(); Mock.pump(40); Mock.Focused=nil; Mock.MousePosition=nil
        Mock.Services.UserInputService.TouchEnabled=false
        assert(Mock.Connections==0,"Workflow leaked connections: "..Mock.Connections)
    end
    local function filesystem()
        local fs={Files={},Folders={}}
        readfile=function(path) return assert(fs.Files[path],"File not found") end
        writefile=function(path,text) assert(not fs.FailWrite,"write denied"); fs.Files[path]=text end
        makefolder=function(path) fs.Folders[path]=true end
        isfile=function(path) return fs.Files[path]~=nil end
        isfolder=function(path) return fs.Folders[path]==true end
        return fs
    end
    local function clearFiles() readfile=nil; writefile=nil; makefolder=nil; isfile=nil; isfolder=nil; listfiles=nil end

    test("base Settings tab, gear, soft close, RightShift and reopen launcher",function()
        local window,section,tab=fixture()
        assert(section:AddToggle({Title="Automatic Id"}).Id=="control/1","Built-in settings shifted public automatic IDs")
        assert(window._settingsTab and not window._settingsTab.Hidden and window.ActiveTab==tab)
        window._settingsTab.Button.Activated:Fire(); assert(window._settingsOpen and window.ActiveTab==window._settingsTab)
        window:ShowSettings(false); assert(window.ActiveTab==tab)
        window.CloseButton.Activated:Fire(); assert(not window.Destroyed and not window.Main.Visible and window.Launcher.Visible)
        window.Launcher.Activated:Fire(); assert(window.Main.Visible)
        window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.RightShift),false); assert(not window.Main.Visible)
        window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.RightShift),false); assert(window.Main.Visible)
        finish(window)
        local destructive=fixture({DestroyOnClose=true}); destructive.CloseButton.Activated:Fire()
        assert(destructive.Destroyed); Mock.pump(40); assert(Mock.Connections==0)
    end)
    test("named profile UI saves, selects and restores callbacks and mouse assignments",function()
        local window,section=fixture(); local events={}
        local toggle=section:AddToggle({Id="enabled",Callback=function(v) events.enabled=v end,Keybind=Enum.UserInputType.MouseButton2})
        local slider=section:AddSlider({Id="amount",Min=0,Max=10,Callback=function(v) events.amount=v end})
        toggle:SetValue(true,true); slider:SetValue(7,true)
        window:ShowSettings(true)
        window._settingsControls.ProfileName.Input.Text="Meu preset personalizado"
        window.Controls["__retrobox/config-save"]:Press(); Mock.pump()
        assert(window._settingsControls.Profiles:GetValue()=="Meu preset personalizado")
        assert(not window._settingsControls.Load.Disabled)
        toggle:SetValue(false,true); slider:SetValue(2,true); toggle.Keybind:SetValue(Enum.KeyCode.G,true)
        window._settingsControls.Load:Press(); Mock.pump()
        assert(toggle:GetValue() and slider:GetValue()==7 and events.enabled==true and events.amount==7)
        assert(toggle.Keybind:GetValue()==Enum.UserInputType.MouseButton2)
        events.enabled=nil; window._settingsControls.Load:Press(); Mock.pump(); assert(events.enabled==true)
        finish(window)
    end)
    test("overwriting a profile requires confirmation and Cancel preserves saved values",function()
        local window,section=fixture(); local toggle=section:AddToggle({Id="enabled"})
        assert(window:SaveConfig("default")); toggle:SetValue(true,true)
        window:ShowSettings(true); window.Controls["__retrobox/config-save"]:Press(); Mock.pump()
        assert(window._dialog); window._dialog:Choose(1); Mock.pump()
        assert(window:LoadConfig("default",{Silent=true}) and not toggle:GetValue())
        toggle:SetValue(true,true); window.Controls["__retrobox/config-save"]:Press(); Mock.pump()
        window._dialog:Choose(2); Mock.pump()
        toggle:SetValue(false,true); assert(window:LoadConfig("default",{Silent=true}) and toggle:GetValue())
        finish(window)
    end)
    test("profile index lists custom names in a new execution without listfiles",function()
        local fs=filesystem()
        local window,section=fixture({FileStorage=true,ConfigFolder="RetroBox/Workflow"})
        section:AddToggle({Id="enabled",Default=true})
        assert(window:SaveConfig("Configuração da noite") and window:SaveConfig("Preset 2"))
        assert(fs.Files["RetroBox/Workflow/profiles-index.json"])
        finish(window)
        local nextWindow,nextSection=fixture({FileStorage=true,ConfigFolder="RetroBox/Workflow"})
        local toggle=nextSection:AddToggle({Id="enabled",Default=false})
        assert(#nextWindow:GetConfigNames()==2 and #nextWindow._settingsControls.Profiles.Options==2)
        assert(nextWindow:LoadConfig("Configuração da noite") and toggle:GetValue())
        finish(nextWindow); clearFiles()
    end)
    test("legacy profiles are discovered through optional listfiles with encoded names",function()
        local fs=filesystem(); fs.Folders["RetroBox/Legacy"]=true
        local window=fixture({FileStorage=true,ConfigFolder="RetroBox/Legacy"})
        fs.Files["RetroBox/Legacy/profile-Meu%20save.json"]=window:ExportConfig()
        listfiles=function() return {"RetroBox\\Legacy\\profile-Meu%20save.json","RetroBox/Legacy/unrelated.json"} end
        -- A new adapter captures the newly available enumeration function.
        window:SetStorage(assert(Library:CreateFileStorage("RetroBox/Legacy")))
        assert(window:GetConfigNames()[1]=="Meu save")
        finish(window); clearFiles()
    end)
    test("corrupt profile index and write failures report errors without mutating flags",function()
        local fs=filesystem(); fs.Files["RetroBox/Broken/profiles-index.json"]="broken"
        local window,section=fixture({FileStorage=true,ConfigFolder="RetroBox/Broken"})
        local toggle=section:AddToggle({Id="enabled"})
        local known,err=window:GetConfigNames(); assert(#known==0 and err)
        assert(not window:SaveConfig("test") and not toggle:GetValue())
        assert(fs.Files["RetroBox/Broken/profiles-index.json"]=="broken")
        fs.Files["RetroBox/Broken/profiles-index.json"]=nil; fs.FailWrite=true
        assert(not window:SaveConfig("test") and next(window._profiles)==nil)
        finish(window); clearFiles()
    end)
    test("custom adapters can enumerate profiles while Save and Load remain compatible",function()
        local stored={}
        local adapter={Save=function(n,v) stored[n]=v end,Load=function(n) return stored[n] end,List=function()
            local result={}; for n in pairs(stored) do result[#result+1]=n end; return result
        end}
        local window,section=fixture({Storage=adapter}); section:AddToggle({Id="enabled",Default=true})
        assert(window:SaveConfig("Custom")); finish(window)
        local nextWindow,nextSection=fixture({Storage=adapter}); local toggle=nextSection:AddToggle({Id="enabled"})
        assert(nextWindow._settingsControls.Profiles.Options[1]=="Custom")
        assert(nextWindow:LoadConfig("Custom") and toggle:GetValue()); finish(nextWindow)
    end)
    test("mouse capture changes assignment without triggering actions and round trips JSON",function()
        local window,section=fixture(); local count=0
        local binding=section:AddKeybind({Id="bind",Default=Enum.KeyCode.F,Callback=function() count=count+1 end})
        binding.Button.Activated:Fire()
        window:_inputBegan(input(Enum.UserInputType.MouseButton3),true); Mock.pump()
        assert(binding:GetValue()==Enum.UserInputType.MouseButton3 and binding.Button.Text=="Mouse 3" and count==0)
        window:_inputBegan(input(Enum.UserInputType.MouseButton3),false); Mock.pump(); assert(count==1)
        local json=window:ExportConfig(); binding:SetValue(Enum.KeyCode.G,true)
        assert(window:ImportConfig(json,{Silent=true}) and binding:GetValue()==Enum.UserInputType.MouseButton3)
        assert(not pcall(function() binding:SetValue(Enum.UserInputType.Touch) end))
        finish(window)
    end)
    test("capture cancel, clear, focus loss and keyboard-only window shortcut",function()
        local window,section=fixture(); local binding=section:AddKeybind({Default=Enum.KeyCode.F})
        binding.Button.Activated:Fire(); window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.Escape),false)
        assert(binding:GetValue()==Enum.KeyCode.F)
        binding.Button.Activated:Fire(); window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.Backspace),false)
        assert(binding:GetValue()==Enum.KeyCode.Unknown)
        binding.Button.Activated:Fire(); Mock.Services.UserInputService.WindowFocusReleased:Fire(); assert(window._binding==nil)
        local shortcut=window._settingsControls.Shortcut; shortcut.Button.Activated:Fire()
        window:_inputBegan(input(Enum.UserInputType.MouseButton2),false); assert(window._binding==shortcut)
        window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.H),false); Mock.pump()
        assert(window.ToggleKey==Enum.KeyCode.H)
        finish(window)
    end)
    test("inline toggle shortcuts respect loaded values and Press toggles both ways",function()
        local window,section=fixture(); local toggle=section:AddToggle({Id="combined",Keybind=Enum.KeyCode.F})
        toggle:SetValue(true,true)
        window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.F),false); Mock.pump(); assert(not toggle:GetValue())
        window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.F),false); Mock.pump(); assert(toggle:GetValue())
        local press=section:AddToggle({Id="press",Keybind={Default=Enum.KeyCode.G,Mode="Press"}})
        window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.G),false); Mock.pump(); assert(press:GetValue())
        window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.G),false); Mock.pump(); assert(not press:GetValue())
        assert(toggle.Keybind.Frame.Parent==toggle.Frame and not toggle.Keybind.TitleLabel.Visible)
        toggle:Destroy(); assert(window.Controls["combined/keybind"]==nil); finish(window)
    end)
    test("Hold releases on mouse up, disable and destruction, including external state",function()
        local state=false
        local window,section=fixture()
        local toggle=section:AddToggle({Id="held",Keybind={Default=Enum.UserInputType.MouseButton2,Mode="Hold"},Callback=function(v) state=v end})
        window:_inputBegan(input(Enum.UserInputType.MouseButton2),false); Mock.pump(); assert(state and toggle:GetValue())
        window:_inputEnded(input(Enum.UserInputType.MouseButton2)); Mock.pump(); assert(not state)
        window:_inputBegan(input(Enum.UserInputType.MouseButton2),false); Mock.pump(); toggle:SetDisabled(true); Mock.pump(); assert(not state)
        toggle:SetDisabled(false); window:_inputBegan(input(Enum.UserInputType.MouseButton2),false); Mock.pump(); assert(state)
        finish(window); assert(not state,"Destroy did not release the script's held state")
    end)
    test("processed input, focused text and configuration editing block script shortcuts",function()
        local window,section=fixture(); local count=0
        section:AddKeybind({Default=Enum.UserInputType.MouseButton2,Callback=function() count=count+1 end})
        window:_inputBegan(input(Enum.UserInputType.MouseButton2),true)
        window.Search:CaptureFocus(); window:_inputBegan(input(Enum.UserInputType.MouseButton2),false); window.Search:ReleaseFocus()
        window:ShowSettings(true); window:_inputBegan(input(Enum.UserInputType.MouseButton2),false); Mock.pump(); assert(count==0)
        window:ShowSettings(false); window:_inputBegan(input(Enum.UserInputType.MouseButton2),false); Mock.pump(); assert(count==1)
        finish(window)
    end)
    test("responsive rows combine controls, handle expansion and release IDs on destroy",function()
        local window,section=fixture(); local row=section:CreateRow()
        local toggle=row:AddToggle({Id="row-toggle"}); local dropdown=row:AddDropdown({Id="row-choice",Options={"A","B"}})
        row.Frame.AbsoluteSize=Vector2.new(600,100); row:_layout(); assert(not row.Stacked and toggle.Frame.Size.X.Scale==.5)
        dropdown:SetOpen(true); assert(row.Frame.Size.Y.Offset>=272)
        row.Frame.AbsoluteSize=Vector2.new(300,100); row:_layout(); assert(row.Stacked and toggle.Frame.Size.X.Scale==1)
        row:Destroy(); assert(window.Controls["row-toggle"]==nil and window.Controls["row-choice"]==nil)
        finish(window)
    end)
    test("Button busy feedback prevents duplicate work and recovers from failures",function()
        local window,section=fixture(); local executions=0
        local action=section:AddButton({Title="Work",Feedback=true,Callback=function() executions=executions+1; return false,"Falha de exemplo" end})
        assert(action:Press() and not action:Press() and action.Button.Text==window:_text("running"))
        Mock.pump(); assert(executions==1 and not action._busy and action.Button.Text=="Work" and #window._notifications>0)
        action._callback=function() error("Expected error") end
        local warnings=#Mock.Warnings; action:Press(); Mock.pump(); assert(not action._busy and #Mock.Warnings==warnings+1)
        table.remove(Mock.Warnings); finish(window)
    end)
    test("dialogs route buttons once, support cancellation and block hotkeys",function()
        local window,section=fixture(); local confirmations=0; local actions=0
        section:AddKeybind({Default=Enum.KeyCode.F,Callback=function() actions=actions+1 end})
        local dialog=window:Confirm({Title="Confirmar",Content="Executar?",OnConfirm=function() confirmations=confirmations+1 end})
        window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.F),false); Mock.pump(); assert(actions==0)
        dialog:Choose(2); dialog:Choose(2); Mock.pump(); assert(confirmations==1 and dialog.Destroyed)
        local cancelled=0; window:Confirm({OnCancel=function() cancelled=cancelled+1 end})
        window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.Escape),false); Mock.pump(); assert(cancelled==1)
        local first=window:Dialog({Content="First"}); local second=window:Dialog({Content="Second"}); assert(first.Destroyed)
        second:SetContent("Updated"); assert(second.Content.Text=="Updated")
        finish(window); assert(second.Destroyed)
    end)
    test("search results navigate across tabs without running component callbacks",function()
        local window,section=fixture(); local callbacks=0
        section:AddToggle({Title="Recurso A",Callback=function() callbacks=callbacks+1 end})
        local other=window:CreateTab("Visual"); local visual=other:CreateSection("Colors")
        local target=visual:AddToggle({Id="color",Title="Cor do círculo",Callback=function() callbacks=callbacks+1 end})
        visual:AddToggle({Title="Cor oculta",Visible=false})
        window.Search.Text="cor"; window.Search:CaptureFocus()
        assert(#window._searchMatches==1 and window._searchMatches[1].Control==target and window.SearchResults.Visible)
        window:_inputBegan(input(Enum.UserInputType.Keyboard,Enum.KeyCode.Return),true); Mock.pump()
        assert(window.ActiveTab==other and window._query=="" and not window.SearchResults.Visible and callbacks==0)
        assert(target.Frame.BorderSizePixel==1); Mock.pump(1.6); assert(target.Frame.BorderSizePixel==0)
        finish(window)
    end)
    test("floating buttons work with hidden UI and mirror the linked toggle",function()
        Mock.Services.UserInputService.TouchEnabled=true
        local window,section=fixture(); local calls=0
        local toggle=section:AddToggle({Id="mobile",Floating={Text="ON/OFF"},Callback=function() calls=calls+1 end})
        local floating=toggle.FloatingButton; assert(not floating.Frame.Visible)
        window:Hide(); assert(floating.Frame.Visible)
        floating.Button.Activated:Fire(); Mock.pump(); assert(toggle:GetValue() and calls==1)
        assert(floating.Button.BackgroundColor3==window.Palette.Accent)
