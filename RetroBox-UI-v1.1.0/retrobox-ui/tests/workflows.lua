        toggle:SetDisabled(true); floating.Button.Activated:Fire(); Mock.pump(); assert(calls==1)
        toggle:Destroy(); assert(floating.Destroyed); finish(window)
    end)
    test("floating Hold releases outside the button and when disabled in settings",function()
        Mock.Services.UserInputService.TouchEnabled=true
        local window,section=fixture(); local state=false
        local toggle=section:AddToggle({Floating={Mode="Hold"},Callback=function(value) state=value end})
        window:Hide(); local touch=input(Enum.UserInputType.Touch)
        toggle.FloatingButton.Button.InputBegan:Fire(touch); Mock.pump(); assert(state)
        window:_inputEnded(touch); Mock.pump(); assert(not state)
        toggle.FloatingButton.Button.InputBegan:Fire(touch); Mock.pump(); assert(state)
        window:SetFloatingOptions({Enabled=false}); Mock.pump(); assert(not state and not toggle.FloatingButton.Frame.Visible)
        finish(window)
    end)
    test("floating and launcher appearance persist, validate atomically and reset",function()
        local window,section=fixture(); local toggle=section:AddToggle({Id="float",Floating={MobileOnly=false,Position=Vector2.new(.1,.2)}})
        toggle.FloatingButton:SetPosition(Vector2.new(.8,.7))
        window:SetFloatingOptions({Size=80,Opacity=.5}); window:SetLauncherOptions({Text="ABRIR",Position=Vector2.new(.7,.4)})
        local json=window:ExportConfig()
        window:SetFloatingOptions({Size=44,Opacity=1}); window:SetLauncherOptions({Text="UI"})
        assert(window:ImportConfig(json,{Silent=true}) and window.FloatSize==80 and window.FloatOpacity==.5 and window.LauncherText=="ABRIR")
        assert(window._floatingPositions.float.X==.8 and window.LauncherPosition.X==.7)
        local invalid=window:ExportConfig(true); invalid.Appearance.Floating.Positions.float.X=-1
        assert(not window:ImportConfig(invalid) and window.FloatSize==80)
        assert(not pcall(function() window:SetFloatingOptions({Opacity=false}) end))
        window:Reset(true); assert(window.FloatSize==64 and toggle.FloatingButton.Position.X==.1)
        finish(window)
    end)
    test("profile load cancels stale held callbacks before applying the saved state",function()
        local state=true
        local window,section=fixture()
        local toggle=section:AddToggle({Id="held",Default=false,Keybind={Default=Enum.UserInputType.MouseButton2,Mode="Hold"},Callback=function(v) state=v end})
