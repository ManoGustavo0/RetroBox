        window:_inputBegan(input(Enum.UserInputType.MouseButton2),false)
        assert(toggle:GetValue())
        assert(window:LoadConfig("off")); Mock.pump()
        assert(not toggle:GetValue() and not toggle.Keybind.Active and not state)
        window:_inputEnded(input(Enum.UserInputType.MouseButton2)); Mock.pump(); assert(not state)
        finish(window)
    end)
    test("long touch on a toggle title opens help without invoking its callback",function()
