return function(Mock,Library,test)
    local function fixture()
        local w=Library:CreateWindow({Id="navigation-test",FileStorage=false,ReducedMotion=true})
        local t=w:CreateTab("Return tab"); local s=t:CreateSection({Title="Hidden section",Collapsible=true})
        return w,t,s
    end
    local function finish(w) w:Destroy(); Mock.pump(100); Mock.Warnings={}; assert(Mock.Connections==0,"Navigation leaked connections") end
    test("palette actual pointer activation navigates expands and focuses without executing",function()
        local w,t,s=fixture(); local calls=0; local input=s:AddInput({Id="target-input",Title="Find me",Callback=function() calls=calls+1 end})
        s:SetCollapsed(true,true); local p=w:OpenCommandPalette(); p.Search.Text="Find me"
        assert(p.Rows._section._visible and p.Rows._pool[1].Button.ZIndex>=222)
        p.Rows._pool[1].Button.Activated:Fire(); Mock.pump(); Mock.Services.RunService.RenderStepped:Fire(.1)
        assert(p.Destroyed and not w._overlay and w.ActiveTab==t and not s:IsCollapsed() and input.Input:IsFocused() and calls==0); finish(w)
    end)
    test("palette touch path and keyboard navigation select the visible filtered result",function()
        local w,t,s=fixture(); local calls=0; s:AddToggle({Id="target-toggle",Title="Touch target",Callback=function() calls=calls+1 end})
        local p=w:OpenCommandPalette(); p.Search.Text="Touch target"; local row=p.Rows._pool[1]
        row.Button.InputBegan:Fire({UserInputType=Enum.UserInputType.Touch,Position=Vector2.new(30,40)})
        row.Button.Activated:Fire(); Mock.pump(); assert(p.Destroyed and w.ActiveTab==t and calls==0)
        p=w:OpenCommandPalette(); p.Search.Text="Touch target"; w:_inputBegan({UserInputType=Enum.UserInputType.Keyboard,KeyCode=Enum.KeyCode.Enter},true)
        assert(p.Destroyed and calls==0); finish(w)
    end)
    test("palette tab targets remain stable after an unrelated tab is removed",function()
        local w,t,s=fixture(); local removed=w:CreateTab("Remove"); local target=w:CreateTab("Stable tab")
        local p=w:OpenCommandPalette(); p.Search.Text="Stable tab"; removed:Destroy()
        assert(p:Choose(1) and w.ActiveTab==target); finish(w)
    end)
    test("palette removed hidden and disabled targets are handled without firing callbacks",function()
        local w,t,s=fixture(); local calls=0; local toggle=s:AddToggle({Id="find-target",Title="Find target",Callback=function() calls=calls+1 end})
        local p=w:OpenCommandPalette(); p.Search.Text="Find target"; toggle:Destroy(); assert(not p:Choose(1) and calls==0)
        toggle=s:AddToggle({Id="find-target",Title="Find target",Disabled=true,Callback=function() calls=calls+1 end})
        p=w:OpenCommandPalette(); p.Search.Text="Find target"; assert(p:Choose(1) and calls==0)
        p=w:OpenCommandPalette(); p.Search.Text="Find target"; toggle:SetVisible(false); assert(not p:Choose(1) and calls==0); finish(w)
    end)
    test("palette registered commands require availability confirmation and show actual failures",function()
        local w=fixture(); local calls=0; w:RegisterCommand({Id="explicit",Title="Explicit",Confirm="Run?",Callback=function() calls=calls+1; return false,"Expected command failure" end})
        local p=w:OpenCommandPalette(); p.Search.Text="Explicit"; p.Rows._pool[1].Button.Activated:Fire(); Mock.pump(); assert(calls==0 and w._dialog)
        w._dialog:Choose(2); Mock.pump(); assert(calls==1 and w._actionHistory[#w._actionHistory]:GetStatus().Status=="Failed"); finish(w)
    end)
    test("theme studio close button removes temporary tab and restores previous tab",function()
        local w,t=fixture(); local count=#w.Tabs; local studio=w:OpenThemeStudio(); w:SetTheme("Hacker")
        studio.CloseButton:Press(); Mock.pump(); assert(studio.Destroyed and #w.Tabs==count and w.ActiveTab==t and w.Theme=="Hacker" and not w._themeStudio)
        local reopened=w:OpenThemeStudio(); assert(reopened~=studio and #w.Tabs==count+1); reopened:Close(); finish(w)
    end)
    test("unsaved theme changes support cancel discard and save without losing catalog silently",function()
        local w,t=fixture(); w:DuplicateTheme("Hacker","Personal"); w:SetTheme("Personal")
        local studio=w:OpenThemeStudio(); local before=w:GetThemeColors("Personal").Accent
        w:SetThemeColor("Personal","Accent","#7195DD"); assert(studio:IsDirty())
        assert(not studio:Close() and w._dialog); w._dialog:Choose(3); Mock.pump(); assert(not studio.Destroyed and studio:IsDirty())
        assert(studio:Close("Discard")); assert(w:GetThemeColors("Personal").Accent==before and w.Theme=="Personal" and w.ActiveTab==t)
        studio=w:OpenThemeStudio(); w:SetThemeColor("Personal","Accent","#7195DD"); assert(studio:Close("Save","theme-profile"))
        assert(w:LoadConfig("theme-profile") and w:GetThemeColors("Personal").Accent==Color3.fromRGB(113,149,221)); finish(w)
    end)
    test("palette scroll calculation accounts for scale and settles after native layout",function()
        local w,t,s=fixture(); local target=s:AddInput({Id="far",Title="Far input"})
        w:SetScale(1.5); t.Frame.AbsolutePosition=Vector2.new(0,30); target.Frame.AbsolutePosition=Vector2.new(0,850)
        assert(w:FocusControl(target)); local first=t.Frame.CanvasPosition.Y
        assert(first>300 and target.Input:IsFocused(),"Scroll="..tostring(first).." focused="..tostring(target.Input:IsFocused()).." scale="..tostring(w._actualScale))
        target.Frame.AbsolutePosition=Vector2.new(0,850-first*w._actualScale)
        Mock.Services.RunService.RenderStepped:Fire(.1); assert(math.abs(t.Frame.CanvasPosition.Y-first)<1e-6 and not w._focusNavigation,"After="..tostring(t.Frame.CanvasPosition.Y).." first="..tostring(first).." nav="..tostring(w._focusNavigation))
        finish(w)
    end)
    test("palette focusing a recycled list enables keyboard selection without activating a script",function()
        local w,t,s=fixture(); local list=s:AddVirtualList({Id="list-target",Title="List target",Items={{Id="a",Text="A"},{Id="b",Text="B"}}})
        local p=w:OpenCommandPalette(); p.Search.Text="List target"; p.Rows._pool[1].Button.Activated:Fire()
        assert(w._activeAdvanced==list); w:_inputBegan({UserInputType=Enum.UserInputType.Keyboard,KeyCode=Enum.KeyCode.Down},false)
        assert(list:GetValue()=="b"); finish(w)
    end)
    test("studio cycles preserve resource counts and save failure keeps editor open",function()
        local w=fixture(); local count=Mock.Connections; local resources=w:GetRuntimeStats().Resources
        for _=1,4 do local studio=w:OpenThemeStudio(); assert(studio:Close()); Mock.pump(); assert(Mock.Connections==count and w:GetRuntimeStats().Resources==resources) end
        local studio=w:OpenThemeStudio(); w:DuplicateTheme("Nord","Pending"); assert(not studio:Close("Save","../invalid") and not studio.Destroyed)
        studio:Close("Discard"); finish(w)
    end)
end
