return function(Mock,Library,test)
    local function fixture(options)
        options=options or {}; options.Id="tools-test"; options.ReducedMotion=true; options.FileStorage=false
        local w=Library:CreateWindow(options); local s=w:CreateTab("Demo"):CreateSection("Demo"); return w,s
    end
    local function finish(w) w:Destroy(); Mock.pump(100); Mock.Warnings={}; Mock.YieldingTasks=false; assert(Mock.Connections==0,"Tool leaked connections") end
    test("local theme editing duplicates protects originals and restores the initial palette",function()
        local w=fixture(); local original=Library.Themes.Monokai.Accent
        w:CreateTheme("My theme","Monokai"); w:SetTheme("My theme"); w:SetThemeColor("My theme","Inset","#EFEFEF")
        assert(w.Palette.Inset.R>.9 and Library.Themes.Monokai.Accent==original)
        local json=w:ExportTheme(); local ok,name=w:ImportTheme(json,{Name="Copy"}); assert(ok and name=="Copy")
        assert(not w:ImportTheme(json,{Name="Monokai"})); assert(not w:ImportTheme(json,{Name="Copy"})); assert(w:ImportTheme(json,{Name="Copy",Replace=true}))
        w:RestoreTheme("My theme"); assert(w.Palette.Inset.R<.2)
        w:DeleteTheme("My theme"); assert(w.Theme=="Monokai" and not w._customThemes["My theme"])
        assert(not pcall(function() w:DeleteTheme("Terminal") end)); finish(w)
    end)
    test("theme catalogs round trip profiles while catalog-only loads leave script flags alone",function()
        local w,s=fixture(); local flag=s:AddToggle({Id="enabled",Default=false})
        w:CreateTheme("Saved","Paper"); w:SetTheme("Saved"); flag:SetValue(true,true); assert(w:SaveConfig("themes"))
        flag:SetValue(false,true); w:SetThemeColor("Saved","Surface","#333333")
        assert(w:LoadThemeCatalog("themes")); assert(not flag:GetValue() and w.Theme=="Saved" and w.Palette.Surface.R>.9)
        w:DeleteTheme("Saved"); assert(w:LoadConfig("themes",{Silent=true})); assert(flag:GetValue() and w.Theme=="Saved")
        finish(w)
    end)
    test("advanced appearance validates before applying flags or palette catalogs",function()
        local w,s=fixture(); s:AddToggle({Id="flag"}); local p=w:ExportConfig(true); p.Flags.flag.Value=true
        p.Appearance.Advanced.TextScale=10; assert(not w:ImportConfig(p) and not w:GetFlag("flag"))
        p.Appearance.Advanced.TextScale=1; p.Appearance.Advanced.Themes.Terminal={Base="Retro98",Colors=p.Appearance.ThemeColors}
        assert(not w:ImportConfig(p) and not w:GetFlag("flag")); finish(w)
    end)
    test("help text scale and command shortcut persist and reset with old profiles compatible",function()
        local w,s=fixture(); local c=s:AddInput({Description="Description",Tooltip="Tooltip"})
        w:SetDescriptions(false):SetTooltips({Enabled=false,Delay=.6}):SetTextScale(1.2):SetCommandKey(Enum.KeyCode.F6)
        local json=w:ExportConfig(); w:SetDescriptions(true):SetTooltips({Enabled=true,Delay=.2}):SetTextScale(1):SetCommandKey(Enum.KeyCode.F4)
        assert(w:ImportConfig(json,{Silent=true}) and not w.ShowDescriptions and not w.TooltipsEnabled and w.CommandKey==Enum.KeyCode.F6 and w.TextScale==1.2)
        assert(not c.DescriptionLabel.Visible); w:Reset(true); assert(w.ShowDescriptions and w.TooltipsEnabled and w.TextScale==1 and w.CommandKey==Enum.KeyCode.F4)
        local legacy=w:ExportConfig(true); legacy.Appearance.Advanced=nil; assert(w:ImportConfig(legacy)); finish(w)
    end)
    test("theme studio previews actual cards and charts and reuses its tab",function()
        local w=fixture(); local studio=w:OpenThemeStudio(); local preview=w.Controls["__retrobox/theme-studio/preview-card"]
        assert(preview.Type=="StatCard" and w.Controls["__retrobox/theme-studio/preview-chart"].Plot)
        studio.Name:SetValue("Studio",true); w.Controls["__retrobox/theme-studio/create"]:Press(); Mock.pump(); assert(w.Theme=="Studio")
        studio.Pickers.Inset:SetValue("#FFFFFF"); Mock.pump(); assert(preview.ValueLabel.Parent.BackgroundColor3.R==1 and Library:ContrastRatio(preview.ValueLabel.TextColor3,preview.ValueLabel.Parent.BackgroundColor3)>=4.49999)
        assert(w:OpenThemeStudio()==studio); studio:Destroy(); assert(not w._themeStudio and not w.Controls["__retrobox/theme-studio/preview-card"]); finish(w)
    end)
    test("dashboards reorder resize persist and reset without rebuilding bound widgets",function()
        local w,s=fixture(); local d=s:CreateDashboard({Id="dash",Columns=2,Editable=true}); local state=w:CreateState(3)
        local a=d:AddStatCard({Id="a",State=state,TwoWay=false}); local b=d:AddLineChart({Id="b",Data={1,2}})
        d.Content.AbsoluteSize=Vector2.new(700,400); d:_layoutWidgets(); assert(not d.Stacked and a.Frame.Size.X.Scale==.5)
        local frame=a.Frame; d:SetOrder({"b","a"}); d:SetWidgetLayout("a",{Span=2,Height=220}); assert(a.Frame==frame and a.Frame.Size.X.Scale==1)
        assert(w:SaveConfig("layout")); d:ResetLayout(); assert(d:GetLayout().Order[1]=="a")
        assert(w:LoadConfig("layout",{Silent=true})); assert(d:GetLayout().Order[1]=="b" and d:GetLayout().Widgets.a.Height==220)
        state:Set(9); assert(a:GetValue()==9); d.Content.AbsoluteSize=Vector2.new(300,400); d:_layoutWidgets(); assert(d.Stacked)
        d:ResetLayout(); a:Destroy(); assert(not d._widgets.a and #d:GetLayout().Order==1); finish(w)
    end)
    test("dashboard bad layouts cannot partially mutate flags or widget geometry",function()
        local w,s=fixture(); s:AddToggle({Id="flag"}); local d=s:CreateDashboard({Id="dash"}); d:AddStatCard({Id="card"})
        local p=w:ExportConfig(true); p.Flags.flag.Value=true; p.Appearance.Advanced.Dashboards.dash.Widgets.card.Height=10
        assert(not w:ImportConfig(p) and not w:GetFlag("flag") and d:GetLayout().Widgets.card.Height==140)
        assert(not pcall(function() d:SetOrder({"missing"}) end)); finish(w)
    end)
    test("runtime inspector is opt in observes jobs actions and groups and cleans subscriptions",function()
        local w,s=fixture(); assert(not w._inspector); Mock.YieldingTasks=true
        local job=w:CreateTask({Id="demo",Callback=function(ctx) task.wait(.2); ctx:ThrowIfCancelled(); return 7 end})
        local inspector=w:OpenRuntimeInspector(); assert(not inspector.AllowCancel and inspector.Cancel.Disabled)
        job:Start(); Mock.Services.RunService.RenderStepped:Fire(.1); Mock.pump(); assert(inspector.Snapshot.Tasks[2] or #inspector.Snapshot.Tasks>=1)
        local action=w:RunAction({Group="test",Callback=function() task.wait(.4); return "done" end}); Mock.pump(); inspector:Refresh()
        assert(#inspector.Snapshot.Groups>=1 and #inspector.Snapshot.Actions>=1)
        job:Stop("outside"); Mock.pump(.5); inspector:Refresh(); assert(not job.Requested and #w:GetDiagnostics()==0)
        inspector:Destroy(); assert(not w._inspector and next(job.Status._listeners)==nil and not w.Tasks["__retrobox/inspector-clock"])
        finish(w)
    end)
    test("inspector cancellation requires explicit option and confirmation",function()
        local w=fixture(); local job=w:CreateTask({Id="worker",Start=true,Callback=function() end}); local inspector=w:OpenRuntimeInspector({AllowCancel=true})
        inspector.Tasks:SetValue("worker",true); inspector.Cancel:Press(); Mock.pump(); assert(w._dialog and job.Requested)
        w._dialog:Choose(2); Mock.pump(); assert(not job.Requested); finish(w)
    end)
    test("command registration availability confirmation and managed results",function()
        local w=fixture(); local calls=0
        local cmd=w:RegisterCommand({Id="run",Title="Run",Callback=function() calls=calls+1; return 3 end})
        local action=w:ExecuteCommand("run"); Mock.pump(); assert(action.Result==3 and calls==1)
        w:RegisterCommand({Id="disabled",Title="Disabled",Enabled=false,Callback=function() calls=calls+10 end}); assert(not w:ExecuteCommand("disabled"))
        w:RegisterCommand({Id="confirmed",Title="Confirmed",Confirm="Continue?",Callback=function() calls=calls+1 end})
        local _,reason=w:ExecuteCommand("confirmed"); assert(reason=="confirmation pending" and calls==1); w._dialog:Choose(1); Mock.pump(); assert(calls==1)
        cmd:Destroy(); assert(not w:ExecuteCommand("run")); finish(w)
    end)
    test("palette search navigates without automatic actions and uses keyboard and click choices",function()
        local w,s=fixture(); local calls=0; s:AddButton({Id="target",Title="Feature target",Callback=function() calls=calls+1 end})
        w:RegisterCommand({Id="explicit",Title="Explicit command",Callback=function() calls=calls+10 end})
        local palette=w:OpenCommandPalette(); palette.Search.Text="target"; assert(#palette.Results==1 and calls==0)
        assert(palette:Choose(1)); Mock.pump(); assert(calls==0 and not w._overlay and w.ActiveTab.Title=="Demo")
        palette=w:OpenCommandPalette(); palette.Search.Text="Explicit"; assert(calls==0); palette:OnKey("Enter"); Mock.pump(); assert(calls==10 and not w._overlay)
        palette=w:OpenCommandPalette(); palette:OnKey("Escape"); assert(not w._overlay); finish(w)
    end)
    test("repeated inspector and studio lifetimes return resource and event counts to baseline",function()
        local w=fixture(); local resources=w:GetRuntimeStats().Resources; local connections=Mock.Connections
        local original={}; for record in pairs(w._resources._records) do original[record.Resource]=true end
        local function detail()
            local rows={}; for record in pairs(w._resources._records) do if not original[record.Resource] then
                local r=record.Resource; rows[#rows+1]=tostring(record.Method)..":"..tostring(type(r)=="table" and (r.Id or r.Name or r._owner and r._owner.Type or r.Destroyed) or typeof(r))
            end end
            return "resources="..w:GetRuntimeStats().Resources.."/"..resources..", connections="..Mock.Connections.."/"..connections.." "..table.concat(rows,";")
        end
        for _=1,3 do local inspector=w:OpenRuntimeInspector(); inspector:Destroy(); Mock.pump(1) end
        assert(w:GetRuntimeStats().Resources==resources and Mock.Connections==connections,detail())
        for _=1,3 do local studio=w:OpenThemeStudio(); studio:Destroy(); Mock.pump(1) end
        assert(w:GetRuntimeStats().Resources==resources and Mock.Connections==connections,detail())
        finish(w)
    end)
    test("F4 keyboard focus and overlay teardown follow visibility and tab changes",function()
        local w,s=fixture(); local calls=0; local button=s:AddButton({Callback=function() calls=calls+1 end})
        assert(w:_focusObject(button.Button)); w:_inputBegan({UserInputType=Enum.UserInputType.Keyboard,KeyCode=Enum.KeyCode.Enter},false); Mock.pump(); assert(calls==1)
        w:_inputBegan({UserInputType=Enum.UserInputType.Keyboard,KeyCode=Enum.KeyCode.F4},false); assert(w._overlay)
        w:Hide(); assert(not w._overlay); w:Show(); local menu=w:ContextMenu({Items={{Text="One"}}}); w.ActiveTab:Select(); assert(menu.Destroyed)
        finish(w)
    end)
end
