-- Tooltip state/input/lifetime checks. Typography is measured by the test double.
return function(Mock,Library,test)
    local sequence=0
    local function fixture(options)
        sequence=sequence+1
        local window=Library:CreateWindow({Id="tooltip-test-"..sequence})
        local tab=window:CreateTab("Help"); local section=tab:CreateSection("Help")
        options=options or {Title="Demo",Tooltip="Explicação do recurso."}
        local control=section:AddToggle(options)
        control.Frame.AbsolutePosition=Vector2.new(100,150); control.Frame.AbsoluteSize=Vector2.new(240,30)
        tab.Frame.AbsoluteSize=window.Root.AbsoluteSize
        return window,control,tab,section
    end
    local function finish(window)
        window:Destroy(); Mock.pump(4); Mock.MousePosition=nil
        assert(Mock.Connections==0,"Tooltip leaked events")
    end
    test("tooltip hover delay and leave cancel without changing values",function()
        local callbacks=0
        local window,control=fixture({Title="Demo",Tooltip="Minha explicação.",Callback=function() callbacks=callbacks+1 end})
        control.Frame.MouseEnter:Fire(120,160); Mock.pump(.39)
        assert(not window.TooltipFrame or not window.TooltipFrame.Visible)
        Mock.pump(.02)
        assert(window.TooltipFrame.Visible and window._tooltipBody.Text=="Minha explicação.")
        assert(window._tooltipTitle.Text=="[?] Demo" and not control:GetValue() and callbacks==0)
        control.Frame.MouseLeave:Fire(); assert(not window.TooltipFrame.Visible)
        control.Frame.MouseEnter:Fire(120,160); control.Frame.MouseLeave:Fire(); Mock.pump(1)
        assert(not window.TooltipFrame.Visible and window._pendingTooltip==nil)
        finish(window)
    end)
    test("one tooltip owner, custom title, Tip alias and immutable options",function()
        local window,first,_,section=fixture({Tooltip={Text="Primeiro",Delay=1}})
        local second=section:AddSlider({Title="Segundo",Min=0,Max=10,Tip={Title="Ajuda",Text="Segundo texto",Delay=.05}})
        second.Frame.AbsolutePosition=Vector2.new(400,150); second.Frame.AbsoluteSize=Vector2.new(240,80)
        first.Frame.MouseEnter:Fire(120,160); second.Frame.MouseEnter:Fire(420,160); Mock.pump(.06)
        assert(window._tooltipOwner==second and window._tooltipTitle.Text=="[?] Ajuda")
        local panel=window.TooltipFrame; Mock.pump(1); assert(window._tooltipOwner==second)
        local copy=second:GetTooltip(); copy.Text="Mutated"; assert(second:GetTooltip().Text=="Segundo texto")
        second:SetTip("Texto atualizado"); assert(window.TooltipFrame==panel and window._tooltipBody.Text=="Texto atualizado")
        second:SetTooltip(nil); assert(not panel.Visible and second:GetTooltip()==nil)
        finish(window)
    end)
    test("tooltip hides with tabs, search, settings, visibility and minimize",function()
        local window,control,tab=fixture()
        control:ShowTooltip(); assert(window.TooltipFrame.Visible)
        window:Hide(); assert(not window.TooltipFrame.Visible); window:Show()
        control:ShowTooltip(); window:Minimize(true); assert(not window.TooltipFrame.Visible)
        control:ShowTooltip(); assert(not window.TooltipFrame.Visible); window:Minimize(false)
        control:ShowTooltip(); window:SetSearch("not-found"); assert(not window.TooltipFrame.Visible)
        control:ShowTooltip(); assert(not window.TooltipFrame.Visible); window:SetSearch("")
        local other=window:CreateTab("Other")
        control:ShowTooltip(); other:Select(); assert(not window.TooltipFrame.Visible)
        control:ShowTooltip(); assert(not window.TooltipFrame.Visible); tab:Select()
        control:ShowTooltip(); window:ShowSettings(true); assert(not window.TooltipFrame.Visible)
        control:ShowTooltip(); assert(not window.TooltipFrame.Visible); window:ShowSettings(false)
        control:ShowTooltip(); control:SetVisible(false); assert(not window.TooltipFrame.Visible)
        control:SetVisible(true); control:ShowTooltip(); assert(window.TooltipFrame.Visible)
        finish(window)
    end)
    test("touch long press and tooltip dismissal do not fire the script callback",function()
        local callbacks=0
        local window,control=fixture({Title="Touch",Tooltip="Segure para ler.",Callback=function() callbacks=callbacks+1 end})
        assert(control.TitleLabel.Active and control.DescriptionLabel.Active)
        control.TitleLabel.TouchLongPress:Fire({Vector2.new(120,160)},Enum.UserInputState.Begin)
        assert(window.TooltipFrame.Visible and window._tooltipMode=="touch")
        control.TitleLabel.TouchLongPress:Fire({Vector2.new(120,160)},Enum.UserInputState.End)
        assert(window.TooltipFrame.Visible)
        window.TooltipFrame.Activated:Fire(); assert(not window.TooltipFrame.Visible)
        control.DescriptionLabel.TouchLongPress:Fire({Vector2.new(120,160)},Enum.UserInputState.Begin)
        assert(window.TooltipFrame.Visible)
        window:_inputBegan({UserInputType=Enum.UserInputType.Touch,Position={X=900,Y=600}},true)
        assert(not window.TooltipFrame.Visible and callbacks==0 and not control:GetValue())
        finish(window)
    end)
    test("tooltip stays inside a small viewport and follows theme colors",function()
        local window,control,tab=fixture()
        window.Root.AbsoluteSize=Vector2.new(360,280); tab.Frame.AbsoluteSize=Vector2.new(360,280)
        control:SetTooltip({Text=("Explicação longa.\n"):rep(100),MaxWidth=640})
        control:ShowTooltip(); local panel=window.TooltipFrame
        assert(panel.Visible and panel.Size.X.Offset<=344 and panel.Size.Y.Offset<=264)
        assert(panel.Position.X.Offset>=8 and panel.Position.Y.Offset>=8)
        assert(panel.Position.X.Offset+panel.Size.X.Offset<=352 and panel.Position.Y.Offset+panel.Size.Y.Offset<=272)
        assert(window._tooltipBody.Position.Y.Offset+window._tooltipBody.Size.Y.Offset<=panel.Size.Y.Offset)
        window:SetTheme("Terminal"); assert(panel.BackgroundColor3==window.Palette.Surface)
        assert(window._tooltipBody.RichText==false and window._tooltipBody.TextTruncate==Enum.TextTruncate.AtEnd)
        local before=control:GetValue(); control:SetDisabled(true); control:ShowTooltip()
        assert(panel.Visible and control:GetValue()==before)
        window.Root.AbsoluteSize=Vector2.new(50,70); control:ShowTooltip(); assert(not panel.Visible)
        finish(window)
    end)
    test("destroy cancels pending and visible tooltips and all events",function()
        local window,control=fixture({Tooltip={Text="Pending",Delay=2}})
        control.Frame.MouseEnter:Fire(120,160); control:Destroy(); Mock.pump(3)
        assert(window._tooltipOwner==nil and window._pendingTooltip==nil)
        local other=window.ActiveTab:CreateSection("Other"):AddToggle({Tooltip="Visible"})
        other:ShowTooltip(); assert(window.TooltipFrame.Visible)
        finish(window)
        local pendingWindow,pending=fixture({Tooltip={Text="Later",Delay=2}})
        pending.Frame.MouseEnter:Fire(120,160); finish(pendingWindow)
        assert(pendingWindow._pendingTooltip==nil and pendingWindow._tooltipOwner==nil)
    end)
    test("invalid tooltip options fail before registering controls",function()
        local window,control,_,section=fixture()
        local count=#section.Controls
        for _,tip in ipairs({true,{}, {Text=12},{Text="bad",Delay=-1},{Text="bad",Delay=4},{Text="bad",MaxWidth=false},{Text=("x"):rep(4097)},{Title=12,Text="bad"}}) do
            assert(not pcall(function() section:AddToggle({Id="invalid-tooltip",Tooltip=tip}) end))
            assert(window.Controls["invalid-tooltip"]==nil and #section.Controls==count)
        end
        local old=control:GetTooltip().Text
        assert(not pcall(function() control:SetTooltip({Text="bad",Delay=false}) end))
        assert(control:GetTooltip().Text==old)
        for _,options in ipairs({{TooltipDelay=false},{TooltipDelay=-1},{TooltipMaxWidth=false},{TooltipMaxWidth=100}}) do
            assert(not pcall(function() Library:CreateWindow(options) end))
        end
        assert(window:ExportConfig():find('"Tooltip"',1,true)==nil)
        finish(window)
    end)
    test("tooltip pointer movement, clipping, drag and focus release",function()
        local window,control=fixture()
        control.Frame.MouseEnter:Fire(120,160); Mock.pump(.5)
        Mock.MousePosition=Vector2.new(130,160)
        Mock.Services.UserInputService.InputChanged:Fire({UserInputType=Enum.UserInputType.MouseMovement})
        assert(window.TooltipFrame.Visible and window._tooltipAnchor.X==130)
        Mock.MousePosition=Vector2.new(600,600)
        Mock.Services.UserInputService.InputChanged:Fire({UserInputType=Enum.UserInputType.MouseMovement})
        assert(not window.TooltipFrame.Visible)
        control.Frame.MouseEnter:Fire(120,160); control.Frame.AbsolutePosition=Vector2.new(100,900); Mock.pump(.5)
        assert(not window.TooltipFrame.Visible)
        control.Frame.AbsolutePosition=Vector2.new(100,150); control:ShowTooltip()
        Mock.Services.UserInputService.WindowFocusReleased:Fire(); assert(not window.TooltipFrame.Visible)
        control:ShowTooltip()
        window:_beginDrag(control,{UserInputType=Enum.UserInputType.MouseButton1},function() end)
        assert(not window.TooltipFrame.Visible); control:ShowTooltip(); assert(not window.TooltipFrame.Visible)
        window:_endDrag(); finish(window)
    end)
end
