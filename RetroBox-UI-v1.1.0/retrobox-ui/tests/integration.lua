return function(Mock,Library,test)
    local function fixture(options)
        Mock.YieldingTasks=true; options=options or {}; options.Id="runtime-integration"; options.FileStorage=false; options.Settings=false; options.ReducedMotion=true
        return Library:CreateWindow(options)
    end
    local function finish(w)
        w:Destroy(); Mock.pump(100); Mock.YieldingTasks=false; Mock.Warnings={}
        assert(w:GetRuntimeStats().WaitingActions==0 and Mock.Connections==0)
    end
    local function tick(dt) Mock.pump(dt or .1); Mock.Services.RunService.RenderStepped:Fire(dt or .1); Mock.pump() end
    test("AwaitAction resumes with original results without polling or subscriptions",function()
        local w=fixture(); local expected={Count=3}; local action=w:RunAction({Callback=function() task.wait(.5); return expected end})
        local response; task.spawn(function() response=table.pack(action:Await({Timeout=2})) end)
        Mock.pump(); assert(not response and w:GetRuntimeStats().WaitingActions==1 and next(action.Status._listeners)==nil)
        Mock.pump(.6); assert(response[1] and response[2]==expected and response[3]=="Completed" and w:GetRuntimeStats().WaitingActions==0)
        assert(w:AwaitAction(action)==true); finish(w)
    end)
    test("await reports failure and can raise through protected callbacks",function()
        local w=fixture(); local action=w:RunAction({Callback=function() task.wait(.1); return false,"failed operation" end})
        local ok,err,status; task.spawn(function() ok,err,status=w:AwaitAction(action) end); Mock.pump(); Mock.pump(.2)
        assert(not ok and err=="failed operation" and status=="Failed")
        local raised,message=pcall(function() action:Await({Throw=true}) end); assert(not raised and tostring(message):find("failed operation",1,true)); finish(w)
    end)
    test("timeout stops only the wait unless cancelling the action is explicit",function()
        local w=fixture(); local action=w:RunAction({Callback=function(ctx) task.wait(1); ctx:ThrowIfCancelled(); return 5 end})
        local response; task.spawn(function() response=table.pack(action:Await({Timeout=.1})) end); Mock.pump(); Mock.pump(.2)
        assert(not response[1] and response[3]=="TimedOut" and not action.Context:IsCancelled() and w:GetRuntimeStats().WaitingActions==0)
        task.spawn(function() response=table.pack(action:Await({Timeout=.1,CancelAction=true})) end); Mock.pump(); Mock.pump(.2)
        assert(response[3]=="TimedOut" and action:GetStatus().Status=="Cancelling"); Mock.pump(1); assert(action:GetStatus().Status=="Cancelled"); finish(w)
    end)
    test("task context cancellation removes its wait while another action continues",function()
        local w=fixture(); local action=w:RunAction({Group="independent",Callback=function() task.wait(1); return "ok" end})
        local result; local job=w:CreateTask({Id="wait",Callback=function(ctx) result=table.pack(ctx:AwaitAction(action)) end})
        job:Start(); tick(); assert(w:GetRuntimeStats().WaitingActions==1); job:Stop("user")
        Mock.pump(); assert(result[3]=="Cancelled" and not action.Context:IsCancelled() and not job:IsRunning()); finish(w)
    end)
    test("context cancellation can propagate to an explicitly owned action",function()
        local w=fixture(); local action=w:RunAction({Callback=function(ctx) task.wait(1); ctx:ThrowIfCancelled() end})
        local job=w:CreateTask({Id="wait",Callback=function(ctx) ctx:AwaitAction(action,{CancelAction=true,Throw=true}) end})
        job:Start(); tick(); job:Stop("user"); Mock.pump(); assert(action.Context:IsCancelled() and #w:GetDiagnostics()==0); finish(w)
    end)
    test("completed, destroyed and self queued handles do not strand waiters",function()
        local w=fixture(); local action=w:RunAction({Callback=function() return 7 end}); Mock.pump(); action:Destroy()
        local ok,value=w:AwaitAction(action); assert(ok and value==7)
        local slow=w:RunAction({Callback=function() task.wait(1) end}); local result
        task.spawn(function() result=table.pack(slow:Await()) end); Mock.pump(); slow:Destroy(); Mock.pump(); assert(result[3]=="Cancelled")
        local nested=w:RunAction({Group="nested",Callback=function(ctx)
            local nextAction=w:RunAction({Group="nested",Policy="Queue",Callback=function() return 1 end})
            local accepted,_,status=ctx:AwaitAction(nextAction); assert(not accepted and status=="Rejected")
            return "safe"
        end}); Mock.pump(); assert(nested.Result=="safe"); finish(w)
    end)
    test("many waiters settle once and timers are released on early completion",function()
        local w=fixture(); local action=w:RunAction({Callback=function() task.wait(.2); return 10 end}); local count=0
        for _=1,20 do task.spawn(function() local ok,value=action:Await({Timeout=60}); assert(ok and value==10); count=count+1 end) end
        Mock.pump(); assert(w:GetRuntimeStats().WaitingActions==20); Mock.pump(.3)
        assert(count==20 and w:GetRuntimeStats().WaitingActions==0 and next(action._awaiters)==nil)
        local longTimers=0; for _,item in ipairs(Mock.Queue) do if item.Due>Mock.Time+40 then longTimers=longTimers+1 end end
        assert(longTimers==0); finish(w)
    end)
    test("window destruction wakes pending awaits and clears ownership",function()
        local w=fixture(); local action=w:RunAction({Callback=function(ctx) task.wait(1); ctx:ThrowIfCancelled() end}); local response
        task.spawn(function() response=table.pack(action:Await()) end); Mock.pump(); w:Destroy(); Mock.pump()
        assert(response and response[3]=="Cancelled" and w:GetRuntimeStats().WaitingActions==0); finish(w)
    end)
    test("periodic tasks queue in shared action groups and publish valid phases",function()
        local w=fixture(); local active,maximum,calls=0,0,0
        w:RunAction({Group="processing",Callback=function() active=active+1; task.wait(.5); active=active-1 end})
        local job=w:CreateTask({Id="periodic",Group="processing",Interval=.1,Callback=function(ctx)
            active=active+1; maximum=math.max(maximum,active); calls=calls+1; assert(ctx.Task==job or ctx.Task.Id=="periodic")
            task.wait(.5); active=active-1; ctx:ThrowIfCancelled(); return "done"
        end})
        local phases={}; w:Manage(job:Subscribe(function(s) phases[#phases+1]=s.Status end),"Disconnect")
        job:Start(); tick(.1); assert(job:GetStatus().Status=="WaitingForGroup" and not job:GetStatus().Running and calls==0)
        tick(.5); assert(job:GetStatus().Status=="Running" and calls==1)
        tick(.2); assert(calls==1); tick(.4)
        assert(job:GetStatus().Status=="Waiting" and job:GetStatus().LastResult=="done" and maximum==1)
        assert(job:GetStatus().NextRun>=Mock.Time and job:GetStatus().Remaining<=.100001 and #phases>=3)
        job:Stop(); finish(w)
    end)
    test("cancelling a queued task removes the queued action and never runs its callback",function()
        local w=fixture(); local blocked=w:RunAction({Group="shared",Callback=function() task.wait(1) end}); local calls=0
        local job=w:CreateTask({Id="queued",Group="shared",Callback=function() calls=calls+1 end})
        job:Start(); tick(); assert(#w._groups.shared.Queue==1); job:Stop("toggle off"); Mock.pump()
        assert(calls==0 and #w._groups.shared.Queue==0 and job:GetStatus().Status=="Stopped" and not blocked.Context:IsCancelled())
        assert(w:GetRuntimeStats().WaitingActions==0); finish(w)
    end)
    test("task ignore, reject and replace policies reuse the existing exclusion manager",function()
        local w=fixture(); local blocked=w:RunAction({Group="shared",Callback=function(ctx) task.wait(1); ctx:ThrowIfCancelled() end})
        local ignored=w:CreateTask({Id="ignore",Group="shared",Policy="Ignore",Callback=function() error("should not run") end})
        local rejected=w:CreateTask({Id="reject",Group="shared",Policy="Reject",Callback=function() error("should not run") end})
        ignored:Start(); rejected:Start(); tick()
        assert(ignored.Requested and ignored.LastOutcome=="Skipped" and rejected:GetStatus().Status=="Failed")
        ignored:Stop(); local count=0
        local replacement=w:CreateTask({Id="replace",Group="shared",Policy="Replace",Callback=function() count=count+1 end})
        replacement:Start(); tick(); assert(blocked.Context:IsCancelled() and count==0)
        tick(1); assert(count==1 and replacement.LastOutcome=="Completed"); replacement:Stop(); finish(w)
    end)
    test("task status uses monotonic deadlines without emitting every frame",function()
        local w=fixture(); local events=0; local job=w:CreateTask({Id="time",Interval=10,Immediate=false,Callback=function() return 42 end})
        w:Manage(job:Subscribe(function() events=events+1 end),"Disconnect"); job:Start(); local nextRun=job:GetStatus().NextRun; local initialEvents=events
        for _=1,10 do tick(.1) end
        assert(events==initialEvents and job:GetStatus().NextRun==nextRun and job:GetStatus().Remaining<10)
        assert(not pcall(function() job.Status:Set({}) end)); job:SetInterval(5); assert(job:GetStatus().Interval==5)
        job:Stop("paused"); assert(job:GetStatus().StopReason=="paused" and not job:GetStatus().NextRun); finish(w)
    end)
    test("toggle bindings synchronize startup, errors, external stops and rapid restarts",function()
        local w=fixture(); local s=w:CreateTab("Main"):CreateSection("Controls"); local toggle=s:AddToggle({Id="toggle"})
        local fail,invalidPhase=false,false; local active,maximum=0,0
        local job=w:CreateTask({Id="bound",Callback=function(ctx) active=active+1; maximum=math.max(maximum,active); task.wait(.5); active=active-1; ctx:ThrowIfCancelled(); if fail then error("failed") end end})
        w:Manage(job:Subscribe(function(status) if status.Status=="Running" and not status.Running then invalidPhase=true end end),"Disconnect")
        toggle:BindTask(job); toggle:SetValue(true,true); tick(); assert(job.Requested and toggle:GetValue())
        toggle:SetValue(false,true); toggle:SetValue(true,true); tick(.1); assert(maximum==1)
        tick(.5); tick(.1); job:Stop("external"); assert(not toggle:GetValue()); tick(1)
        fail=true; toggle:SetValue(true,true); tick(); tick(.6)
        assert(not invalidPhase and job:GetStatus().Status=="Failed" and not toggle:GetValue() and job.LastError:find("failed",1,true)); finish(w)
    end)
    test("task bindings distinguish requested state from continued or stopped work",function()
        local w=fixture(); local s=w:CreateTab("Main"):CreateSection("Controls")
        local toggle=s:AddToggle({Default=true}); local job=w:CreateTask({Id="keep",OnError="Continue",Callback=function() error("retryable") end})
        toggle:BindTask(job,{OnStop="KeepRequested"}); tick(); assert(toggle:GetValue() and job.Requested and job:GetStatus().Status=="Waiting")
        job:Stop("external"); assert(toggle:GetValue() and not job.Requested)
        toggle:SetValue(false,true); toggle:SetValue(true,true); assert(job.Requested)
        toggle:Destroy(); assert(not job.Requested); finish(w)
    end)
    test("binding from task state and replacing bindings releases listeners",function()
        local w=fixture(); local s=w:CreateTab("Main"):CreateSection("Controls"); local toggle=s:AddToggle()
        local job=w:CreateTask({Id="started",Start=true,Callback=function() end})
        local binding=toggle:BindTask(job,{Initial="Task",StopOnUnbind=false}); assert(toggle:GetValue())
        binding:Destroy(); assert(job.Requested and next(job.Status._listeners)==nil)
        toggle:BindTask(job,{Initial="Task"}); job:Destroy(); assert(not toggle:GetValue())
        local source=w:CreateScope(); local closed=w:CreateTask({Id="closed",Scope=source,Callback=function() end}); source:Destroy()
        local failed=s:AddToggle({Default=true}); failed:BindTask(closed); assert(not failed:GetValue() and not closed.Requested)
        finish(w)
    end)
    test("immediate scheduler completion and cancellation during Running do not race",function()
        local w=fixture(); Mock.ImmediateSpawns=true
        local action=w:RunAction({Callback=function() return 9 end}); local ok,value=action:Await(); assert(ok and value==9)
        local calls=0; local job=w:CreateTask({Id="race",Group="race",Callback=function() calls=calls+1 end})
        w:Manage(job:Subscribe(function(status) if status.Status=="Running" then job:Stop("observer") end end),"Disconnect")
        job:Start(); tick(); assert(calls==0 and job:GetStatus().Status=="Stopped" and w:GetRuntimeStats().WaitingActions==0)
        Mock.ImmediateSpawns=false; finish(w)
    end)
end
