return function(Mock,Library,test)
    local function fixture()
        Mock.AnimatedTweens=true
        local w=Library:CreateWindow({Id="animation-test",FileStorage=false,Settings=false})
        local s=w:CreateTab("Main"):CreateSection({Title="Controls",Collapsible=true})
        Mock.pump(1); return w,s
    end
    local function finish(w) w:Destroy(); Mock.pump(100); Mock.AnimatedTweens=false; Mock.YieldingTasks=false; assert(Mock.Connections==0); Mock.Warnings={} end
    test("animator cancels overlapping properties and preserves independent tracks",function()
        local w,s=fixture(); local object=Instance.new("Frame"); object.Parent=s.Frame
        local old=w:_animate(object,{BackgroundTransparency=.5},.2,"first")
        local independent=w:_animate(object,{Size=UDim2.fromOffset(10,10)},.2,"size")
        w:_animate(object,{BackgroundTransparency=.2},.1,"next")
        assert(old.PlaybackState==Enum.PlaybackState.Cancelled and old.Destroyed and not independent.Destroyed)
        Mock.pump(1); assert(object.BackgroundTransparency==.2 and object.Size.X.Offset==10 and w:GetRuntimeStats().Animations==0)
        object:Destroy(); finish(w)
    end)
    test("rapid hide and show resolve to logical visibility and block hidden clicks",function()
        local w,s=fixture(); local n=0; local b=s:AddButton({Callback=function() n=n+1 end})
        w:Hide(); assert(not w._shown and w.Main.Visible and w.Launcher.Visible); b.Button.Activated:Fire(); Mock.pump(); assert(n==0)
        w:Show(); w:Hide(); w:Show(); Mock.pump(1)
        assert(w._shown and w.Main.Visible and w.Main.BackgroundTransparency==0 and w.ScaleObject.Scale==w._actualScale)
        b.Button.Activated:Fire(); Mock.pump(1); assert(n==1); finish(w)
    end)
    test("reduced motion and disabled animations finish pending transitions",function()
        local w,s=fixture(); local toggle=s:AddToggle({Default=false}); toggle:SetValue(true)
        assert(w:GetRuntimeStats().Animations>0); w:SetReducedMotion(true); assert(w:GetRuntimeStats().Animations==0)
        w:Hide(); assert(not w.Main.Visible); w:Show(); assert(w.Main.Visible)
        w:SetReducedMotion(false); w:SetAnimations({Enabled=false,Speed=2,Intensity="Subtle"}); w:Hide(); assert(not w.Main.Visible)
        local options=w:GetAnimations(); options.Speed=4; assert(w:GetAnimations().Speed==2); finish(w)
    end)
    test("animation and drag preferences round trip and legacy profiles remain valid",function()
        local w=fixture(); w:SetAnimations({Enabled=false,Speed=1.5,Intensity="Subtle"}); w:SetDragOptions({Smooth=false,Responsiveness=40})
        local json=w:ExportConfig(); w:SetAnimations({Enabled=true,Speed=1,Intensity="Normal"}); w:SetDragOptions({Smooth=true,Responsiveness=24})
        assert(w:ImportConfig(json,{Silent=true}) and not w.Animations.Enabled and w.Animations.Speed==1.5 and not w.SmoothDragging and w.DragResponsiveness==40)
        local old=Mock.Services.HttpService:JSONDecode(json); old.Appearance.Animations=nil; old.Appearance.Drag=nil
        assert(w:ImportConfig(Mock.Services.HttpService:JSONEncode(old),{Silent=true}))
        old.Appearance.Animations={Speed=0}; local before=w:GetAnimations(); assert(not w:ImportConfig(Mock.Services.HttpService:JSONEncode(old)) and w.Animations.Speed==before.Speed)
        w:Reset(true); assert(w.Animations.Enabled and w.Animations.Speed==1 and w.SmoothDragging); finish(w)
    end)
    test("collapsible sections cancel reversals and search expands the destination",function()
        local w,s=fixture(); local b=s:AddButton({Id="target"}); s:SetCollapsed(true); b.Button.Activated:Fire(); assert(not b._busy)
        s:SetCollapsed(false); s:SetCollapsed(true); Mock.pump(1); assert(not s.Content.Visible and s:IsCollapsed())
        assert(w:FocusControl("target")); Mock.pump(1); assert(s.Content.Visible and not s:IsCollapsed()); finish(w)
    end)
    test("notification capacity and window destruction tolerate in flight exits",function()
        local w=fixture(); local notice=w:Notify({Content="one",Kind="loading"}); notice:Destroy()
        for i=1,8 do w:Notify({Content=tostring(i),Kind="warning"}) end
        assert(#w._notifications==4); w._notifications[1]:Destroy(); finish(w); assert(#w._notifications==0)
    end)
    test("dialogs block repeated choices and retain the modal barrier during exit",function()
        local w,s=fixture(); local n=0; local underlying=s:AddButton({Callback=function() n=n+100 end})
        local d=w:Dialog({Buttons={{Text="OK",Callback=function() n=n+1 end}}})
        underlying.Button.Activated:Fire(); d:Choose(1); d:Choose(1); Mock.pump()
        assert(n==1 and w._dialog==d); underlying.Button.Activated:Fire(); Mock.pump(); assert(n==1)
        local replacement=w:Dialog({Content="next"}); assert(w._dialog==replacement and not d.Frame.Parent)
        Mock.pump(1); replacement:Close(); Mock.pump(1); assert(not w._dialog); finish(w)
    end)
    test("window drag interpolates within bounds without relaying out controls",function()
        local w=fixture(); local layouts=0; local original=w._layout
        w._layout=function(self) layouts=layouts+1; return original(self) end
        local start=w.Main.Position.X.Offset; w:_moveWindow(Vector2.new(start+70,w.Main.Position.Y.Offset))
        for i=1,30 do Mock.Services.RunService.RenderStepped:Fire(1/60) end
        assert(w.Main.Position.X.Offset>start and layouts==0 and not w._dragRender)
        w:_moveWindow(Vector2.new(-10000,-10000)); w:SetReducedMotion(true)
        assert(w.Main.Position.X.Offset>=w._logicalSize.X*w._actualScale/2 and not w:GetRuntimeStats().FrameConnection)
        finish(w)
    end)
    test("rapid minimize and restore preserve the rendered header position",function()
        local w=fixture(); local size,position=w.Main.Size,w.Main.Position
        w:Minimize(true); w:Minimize(false); Mock.pump(1)
        assert(not w.Minimized and w.Main.Size.Y.Offset==size.Y.Offset and w.Main.Position.Y.Offset==position.Y.Offset)
        w:Minimize(true); Mock.pump(1); local top=w.Main.Position.Y.Offset-w.Main.Size.Y.Offset*w._actualScale/2
        assert(math.abs(top-(position.Y.Offset-size.Y.Offset*w._actualScale/2))<.01); finish(w)
    end)
    test("destroying an animated component releases every tween subscription",function()
        local w,s=fixture(); local c=s:AddLineChart({Data={1,2,3},Animated=true})
        Mock.pump(.1); Mock.Services.RunService.RenderStepped:Fire(.1); c:SetData({3,2,1}); Mock.Services.RunService.RenderStepped:Fire(.1)
        Mock.DeferDestroying=true; c.Frame:Destroy(); Mock.pump(); Mock.DeferDestroying=false
        assert(c.Destroyed and w:GetRuntimeStats().QueuedVisuals==0 and w:GetRuntimeStats().Animations==0); finish(w)
    end)
    test("mouse and touch drag preserve the grab offset and release on focus loss",function()
        local w=fixture(); w:SetReducedMotion(true)
        local header=w.TitleLabel.Parent; local center=Vector2.new(640,360)
        w.Main._props.AbsolutePosition=Vector2.new(center.X-w.Main.AbsoluteSize.X/2,center.Y-w.Main.AbsoluteSize.Y/2)
        header._props.AbsolutePosition=Vector2.new(249,79)
        local other=Library:CreateWindow({Id="independent",Settings=false,FileStorage=false,ReducedMotion=true}); local otherPosition=other.Main.Position.X.Offset
        for _,kind in ipairs({Enum.UserInputType.MouseButton1,Enum.UserInputType.Touch}) do
            Mock.MousePosition=Vector2.new(400,90)
            local input={UserInputType=kind,Position=Vector2.new(400,90)}; header.InputBegan:Fire(input)
            if kind==Enum.UserInputType.Touch then
                local foreign={UserInputType=kind,Position=Vector2.new(900,500)}; Mock.Services.UserInputService.InputChanged:Fire(foreign)
                assert(w.Main.Position.X.Offset==640)
                input.Position=Vector2.new(450,120); Mock.Services.UserInputService.InputChanged:Fire(input)
            else Mock.MousePosition=Vector2.new(450,120); Mock.Services.UserInputService.InputChanged:Fire({UserInputType=Enum.UserInputType.MouseMovement,Position=Vector2.new(450,120)}) end
            assert(w.Main.Position.X.Offset==690 and w.Main.Position.Y.Offset==390 and other.Main.Position.X.Offset==otherPosition)
            Mock.Services.UserInputService.InputEnded:Fire(input); assert(not w._drag)
        end
        header.InputBegan:Fire({UserInputType=Enum.UserInputType.MouseButton1,Position=Vector2.new(400,90)})
        Mock.Services.UserInputService.WindowFocusReleased:Fire(); assert(not w._drag)
        Mock.MousePosition=nil; other:Destroy(); finish(w)
    end)
    test("window transitions allow pending component transitions to finish",function()
        local w,s=fixture(); local picker=s:AddColorPicker({Default="#112233"})
        picker:SetOpen(true); w:Hide(); w:Show(); Mock.pump(1)
        assert(picker.Open and picker.Frame.Size.Y.Offset>100)
        s:SetCollapsed(true); w:Hide(); w:Show(); Mock.pump(1)
        assert(s:IsCollapsed() and not s.Content.Visible); finish(w)
    end)
end
