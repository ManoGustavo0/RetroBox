return function(Mock,Library,test)
    local function finish(hub)
        hub.Window:Destroy(); Mock.pump(100)
        Mock.ThumbnailDelay=nil; Mock.ThumbnailError=nil; Mock.TeleportError=nil
        Mock.TeleportRequests={}; Mock.ThumbnailRequests={}; Mock.Warnings={}; Mock.YieldingTasks=false
        assert(Mock.Connections==0,"Hub leaked connections")
    end
    local function gameRecord(id,place,callback)
        return {Id=id,Name=id,PlaceId=place,UniverseId=place+10000,Scripts={{Id="main",Title="Main "..id,Callback=callback or function() return {Done=true} end}}}
    end
    local function fixture(options)
        options=options or {}; options.Id="hub-test"; options.FileStorage=false; options.ReducedMotion=true
        options.Games=options.Games or {gameRecord("current",game.PlaceId),gameRecord("other",2222)}
        return Library:CreateScriptHub(options)
    end
    local function readable(control)
        local scale=math.max(.01,control._window._actualScale or 1)
        local size=Mock.Services.TextService:GetTextSize(control.TitleLabel.Text,control.TitleLabel.TextSize,control.TitleLabel.Font,Vector2.new(math.max(1,control.TitleLabel.AbsoluteSize.X/scale),100000))
        assert(control.TitleLabel.Size.Y.Offset>=size.Y,"Hub detail text is clipped")
        assert(control.Frame.Size.Y.Offset>=control.TitleLabel.Size.Y.Offset,"Hub detail text exceeds its row")
        assert(control.TitleLabel.TextWrapped and control.TitleLabel.TextYAlignment==Enum.TextYAlignment.Top)
    end
    test("game and script descriptions remain readable after selection and text scaling",function()
        local calls=0; local rec=gameRecord("current",game.PlaceId,function() calls=calls+1 end)
        rec.Description="Descrição do jogo.\nSegunda linha do jogo.\nTerceira linha."
        rec.Scripts[1].Description="Descrição do script.\nOutra linha de instruções.\nMais informações do script."
        local h=fixture({Games={rec}}); Mock.pump()
        assert(h.GameDetails.TitleLabel.Text:find(rec.Description,1,true))
        assert(h.ScriptDetails.TitleLabel.Text:find(rec.Scripts[1].Description,1,true))
        for _,scale in ipairs({.8,1,1.4}) do h.Window:SetTextScale(scale); readable(h.GameDetails); readable(h.ScriptDetails) end
        h.Window:SetDescriptions(false); readable(h.GameDetails); readable(h.ScriptDetails)
        assert(h.GameDetails.TitleLabel.Text:find(rec.Description,1,true) and calls==0)
        h:Hide(); h:Show(); readable(h.GameDetails); readable(h.ScriptDetails); finish(h)
    end)
    test("description edits expand long details and reclaim space when content becomes short",function()
        local h=fixture(); Mock.pump()
        local long=("Informações adicionais sobre o jogo e seus scripts. "):rep(25)
        h:UpdateGame("current",{Description=long}); h:UpdateScript("current","main",{Description=long})
        readable(h.GameDetails); readable(h.ScriptDetails)
        local gameHeight,scriptHeight=h.GameDetails.Frame.Size.Y.Offset,h.ScriptDetails.Frame.Size.Y.Offset
        h:UpdateGame("current",{Description="Breve descrição."}); h:UpdateScript("current","main",{Description="Texto curto."})
        readable(h.GameDetails); readable(h.ScriptDetails)
        assert(h.GameDetails.Frame.Size.Y.Offset<gameHeight and h.ScriptDetails.Frame.Size.Y.Offset<scriptHeight)
        finish(h)
    end)
    test("hub is optional and empty catalogs have no fabricated entries or actions",function()
        local w=Library:CreateWindow({Id="traditional",FileStorage=false}); assert(not w._scriptHubs); w:Destroy(); Mock.pump(100)
        local h=fixture({Games={}}); assert(#h:GetGames()==0 and not h.SelectedGameId and h.PlayButton.Disabled and h.FavoriteButton.Disabled)
        assert(h.ScriptList.EmptyLabel.Text:find("script")); finish(h)
    end)
    test("auto detection prefers PlaceId and never runs scripts or teleports",function()
        local calls=0; local first=gameRecord("universe",9876); first.UniverseId=game.GameId
        local h=fixture({Games={first,gameRecord("exact",game.PlaceId,function() calls=calls+1 end)}})
        Mock.pump(); assert(h.SelectedGameId=="exact" and h:DetectCurrentGame()=="exact" and calls==0 and #(Mock.TeleportRequests or {})==0)
        h:Hide(); h:Show(); assert(h.SelectedGameId=="exact" and calls==0)
        h.Window:Minimize(true); h.Window:Minimize(false); assert(h.SelectedGameId=="exact"); finish(h)
    end)
    test("disabled auto detection and unknown current games keep normal selection",function()
        local h=fixture({AutoDetectGame=false,Games={gameRecord("aaa",2222),gameRecord("current",game.PlaceId)}})
        assert(h.SelectedGameId=="aaa"); assert(h:RemoveGame("aaa") and h.SelectedGameId=="current")
        h:RemoveGame("current"); h:AddGame(gameRecord("outside",3333)); assert(h.SelectedGameId=="outside" and not h:IsCurrentGame("outside")); finish(h)
    end)
    test("game and script registration validate atomically and update the same views",function()
        local h=fixture(); local view=h.GameList.Viewport; local before=#h:GetGames()
        assert(not pcall(function() h:AddGame(gameRecord("current",1)) end)); assert(#h:GetGames()==before)
        assert(not pcall(function() h:UpdateGame("current",{PlaceId=-3}) end)); assert(h:GetGame("current").PlaceId==game.PlaceId)
        assert(not pcall(function() h:UpdateGame("current",{Scripts={{Id="a",Title="A"},{Id="a",Title="B"}}}) end))
        h:AddGame({Id="new",Name="New",PlaceId=4444,Scripts={}}); h:SelectGame("new"); assert(#h.ScriptList.Items==0)
        h:AddScript("new",{Id="first",Title="First",Author="Author",Version="1.0",Callback=function() end})
        h:UpdateScript("new","first",{Title="Renamed"}); assert(h:GetScript("new","first").Title=="Renamed")
        assert(h:RemoveScript("new","first") and #h.ScriptList.Items==0); h:RemoveGame("new")
        assert(h.GameList.Viewport==view); local meta=h:GetGame("current"); meta.Name="changed"; assert(h:GetGame("current").Name=="current"); finish(h)
    end)
    test("queries ignore case including Portuguese capitals and sorting preserves selection",function()
        local h=fixture({Games={{Id="agua",Name="ÁGUA",PlaceId=3333,Scripts={{Id="s",Title="Ação",Author="DEV",Callback=function() end}}},gameRecord("beta",game.PlaceId)}})
        h:SetGameQuery("água"); assert(h.GameList:GetViewStats().Filtered==1)
        h.GameList._pool[1].Button.Activated:Fire(); Mock.pump(); assert(h.SelectedGameId=="agua")
        h:SetScriptQuery("dev"); assert(h.ScriptList:GetViewStats().Filtered==1)
        h:SetScriptQuery("absent"); assert(h.ScriptList:GetViewStats().Filtered==0)
        h:SetGameQuery(""); h:SetFavorite("beta",true); h:SetSort("Favorites")
        assert(h.GameList.Items[1].Id=="beta" and h.SelectedGameId=="agua"); finish(h)
    end)
    test("favorites sort and selection round trip profiles including silent restoration",function()
        local h=fixture(); h:SetFavorite("other",true); h:SelectGame("other"); h:SetSort("Alphabetical")
        assert(h.Window:SaveConfig("hub-profile")); h:SetFavorite("other",false); h:SelectGame("current"); h:SetSort("Order")
        assert(h.Window:LoadConfig("hub-profile",{Silent=true})); Mock.pump()
        assert(h:IsFavorite("other") and h.SelectedGameId=="other" and h.Sort:GetValue()=="Alphabetical")
        h:RemoveGame("other"); assert(not h:IsFavorite("other")); finish(h)
    end)
    test("thumbnail identifiers use UniverseId for GameIcon and PlaceId for GameThumbnail",function()
        local h=fixture({Games={{Id="icon",Name="Icon",PlaceId=9999,UniverseId=555},{Id="place",Name="Place",PlaceId=8888},{Id="custom",Name="Custom",Image="rbxassetid://777"}}})
        Mock.pump(); assert(h:GetThumbnailStatus("icon").URI=="rbxthumb://type=GameIcon&id=555&w=150&h=150")
        assert(h:GetThumbnailStatus("place").URI=="rbxthumb://type=GameThumbnail&id=8888&w=256&h=144")
        assert(h:GetThumbnailStatus("custom").Status=="Loaded")
        local count=#Mock.ThumbnailRequests; h:SelectGame("icon"); h:SelectGame("place"); Mock.pump(); assert(#Mock.ThumbnailRequests==count)
        assert(not pcall(function() h:AddGame({Id="web",Name="Web",Image="https://example.com/img.png"}) end)); finish(h)
    end)
    test("thumbnail failures retain pixel fallback and can be retried",function()
        Mock.ThumbnailError="Asset unavailable"; local h=fixture(); Mock.pump()
        assert(h:GetThumbnailStatus("current").Status=="Unavailable" and h.GameImage:GetValue()=="")
        local row=h.GameList._pool[1]; assert(row.Fallback.Frame.Visible and not row.Thumb.Visible)
        Mock.ThumbnailError=nil; h:RetryThumbnail("current"); Mock.pump(); assert(h:GetThumbnailStatus("current").Status=="Loaded"); finish(h)
    end)
    test("thumbnail queue cache and view stay bounded and pending work cancels on destroy",function()
        local games={}; for i=1,180 do games[i]=gameRecord("game"..i,10000+i) end
        Mock.YieldingTasks=true; Mock.ThumbnailDelay=2
        local h=fixture({Games=games}); Mock.pump()
        for i=1,180 do h:SelectGame("game"..i) end
        assert(h._thumbActive<=4 and #h._thumbOrder<=128 and #h._thumbQueue<=128 and h.GameList:GetViewStats().AllocatedRows<=64)
        finish(h)
    end)
    test("script selection never executes; the single main button rejects duplicate runs",function()
        local calls=0; Mock.YieldingTasks=true
        local h=fixture({Games={gameRecord("current",game.PlaceId,function(ctx) calls=calls+1; task.wait(.5); ctx:ThrowIfCancelled(); return {Done=42} end)}})
        local row=h.ScriptList._pool[1]; row.Button.Activated:Fire(); Mock.pump(); assert(calls==0)
        h.PlayButton:Press(); Mock.pump()
        assert(calls==1 and h:GetScriptStatus("current","main").Status=="Running")
        assert(not h:RunScript("current","main")); h.PlayButton:Press(); Mock.pump(); assert(calls==1)
        Mock.pump(.6); assert(h:GetScriptStatus("current","main").Status=="Completed" and not h._pendingScripts["current/main"]); finish(h)
    end)
    test("disabled missing capabilities and confirmation prevent unrequested actions",function()
        local calls=0; local h=fixture({Games={{Id="current",Name="Current",PlaceId=game.PlaceId,Scripts={{Id="disabled",Title="Disabled",Enabled=false,Callback=function() calls=calls+1 end},{Id="missing",Title="Missing",Requires={"readfile"},Callback=function() calls=calls+1 end},{Id="confirm",Title="Confirm",Confirm="Run?",Callback=function() calls=calls+1 end}}}}})
        local original=readfile; readfile=nil
        assert(not h:RunScript("current","disabled")); assert(not h:RunScript("current","missing")); assert(calls==0)
        local _,reason=h:RunScript("current","confirm"); assert(reason=="confirmation pending"); Mock.pump(); assert(calls==0)
        h.Window._dialog:Choose(1); Mock.pump(); assert(calls==0)
        h:RunScript("current","confirm"); Mock.pump(); h.Window._dialog:Choose(2); Mock.pump(); assert(calls==1)
        readfile=original; finish(h)
    end)
    test("action failure and catalog replacement report the actual result",function()
        local h=fixture({Games={gameRecord("current",game.PlaceId,function() return false,"Expected failure" end)}})
        local handle=h:RunScript("current","main"); Mock.pump(); assert(handle:GetStatus().Status=="Failed" and h:GetScriptStatus("current","main").Error=="Expected failure")
        h:UpdateScript("current","main",{Callback=function() return true end}); local action=h:RunScript("current","main"); Mock.pump(); assert(action:GetStatus().Status=="Completed"); finish(h)
    end)
    test("teleport requires explicit confirmation and never triggers script execution",function()
        local h=fixture(); local calls=#(Mock.TeleportRequests or {}); local handle,reason=h:TeleportToGame("other")
        assert(not handle and reason=="confirmation pending"); Mock.pump(); assert(#(Mock.TeleportRequests or {})==calls)
        h.Window._dialog:Choose(2); Mock.pump(); assert(#Mock.TeleportRequests==calls+1 and Mock.TeleportRequests[#Mock.TeleportRequests].PlaceId==2222)
        assert(h._teleportPending and h.TeleportStatus:GetValue():find("Roblox") and not h:GetScriptStatus("other","main").Result)
        assert(not h:TeleportToGame("other")); finish(h)
    end)
    test("teleport synchronous failure asynchronous failure and timeout never claim arrival",function()
        local h=fixture({ConfirmTeleport=false}); Mock.TeleportError="Denied"; local failed=h:TeleportToGame("other"); Mock.pump()
        assert(failed:GetStatus().Status=="Failed" and not h._teleportPending)
        Mock.TeleportError=nil; h:TeleportToGame("other"); Mock.pump()
        Mock.Services.TeleportService.TeleportInitFailed:Fire(Mock.Services.Players.LocalPlayer,nil,"Async denied",2222)
        assert(not h._teleportPending and h.TeleportStatus:GetValue()=="Async denied")
        h:TeleportToGame("other"); Mock.pump(); Mock.pump(31); assert(not h._teleportPending and h.TeleportStatus:GetValue():find("confirm")); finish(h)
    end)
    test("keyboard focus on the main run button executes the selected script",function()
        local calls=0; local h=fixture({Games={gameRecord("current",game.PlaceId,function() calls=calls+1 end)}})
        h.Window._activeAdvanced=h.ScriptList; local play=h.PlayButton.Button
        assert(h.Window:_focusObject(play)); assert(not h.Window._activeAdvanced)
        h.Window:_inputBegan({UserInputType=Enum.UserInputType.Keyboard,KeyCode=Enum.KeyCode.Enter},false); Mock.pump(); assert(calls==1); finish(h)
    end)
    test("destroying and recreating a hub with the same Id cleans the earlier instance",function()
        local first=fixture(); local second=fixture(); assert(first.Destroyed and first.Window.Destroyed and not second.Destroyed)
        Mock.pump(); assert(second.SelectedGameId=="current"); finish(second)
    end)
    test("removing an in-flight script cooperatively cancels without running its remaining effects",function()
        Mock.YieldingTasks=true; local effects=0
        local h=fixture({Games={gameRecord("current",game.PlaceId,function(ctx) task.wait(1); ctx:ThrowIfCancelled(); effects=effects+1 end)}})
        local action=h:RunScript("current","main"); Mock.pump(); assert(h:RemoveScript("current","main"))
        Mock.pump(2); assert(action:GetStatus().Status=="Cancelled" and effects==0 and not h._pendingScripts["current/main"]); finish(h)
    end)
    test("a developer teleport adapter receives PlaceId and failures remain observable",function()
        local seen; local h=fixture({ConfirmTeleport=false,Teleporter=function(placeId,player,record,ctx)
            seen={placeId,player,record.UniverseId,ctx}; return false,"Adapter rejected request"
        end})
        local action=h:TeleportToGame("other"); Mock.pump(); assert(seen[1]==2222 and seen[2]==Mock.Services.Players.LocalPlayer and seen[3]==12222 and seen[4])
        assert(action:GetStatus().Status=="Failed" and not h._teleportPending); finish(h)
    end)
    test("all themes repaint hub rows without rebuilding catalog or losing selection",function()
        local h=fixture(); h:SelectGame("other"); local list=h.GameList; local viewport=list.Viewport
        for _,name in ipairs(Library:GetThemeNames()) do h.Window:SetTheme(name); assert(h.GameList==list and list.Viewport==viewport and h.SelectedGameId=="other")
            for _,row in ipairs(list._pool) do if row.Button.Visible then assert(Library:ContrastRatio(row.Labels[1].TextColor3,h.Window:_surfaceColor(row.Labels[1]))>=4.49999) end end
        end
        h.Window:_layout(); h.Window:Hide(); h:Show(); assert(h.SelectedGameId=="other"); finish(h)
    end)
end
